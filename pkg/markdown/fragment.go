package markdown

import "proofreader/pkg/xhtml"

// fragment снимает обёртку документа, которую ставит флаг html.CompletePage,
// и возвращает содержимое <body>, пересобранное строгим XHTML.
//
// Ошибка xhtml.Body здесь глушится, и это не небрежность. html.Parse отдаёт
// ошибку только от источника (io.Reader), а источник — всегда
// strings.NewReader, который кроме io.EOF ничего не отдаёт: ветка
// недостижима, на 1400 полосах живого корпуса — ноль отказов. Запасной
// вариант выбран в пользу текста: вернуть страницу как есть хуже разве что
// лишней обёрткой, которую браузер и так выбросит, а вернуть пустоту значило
// бы потерять текст полосы молча.
//
// Зовущие снаружи пакета этой развилки не видят и видеть не должны — в этом
// и смысл контракта.
func fragment(rendered string) string {
	body, err := xhtml.Body(rendered)
	if err != nil {
		return rendered
	}
	return body
}
