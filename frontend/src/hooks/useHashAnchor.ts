import { useEffect } from 'react';
import { useLocation } from 'react-router-dom';
import { jumpToAnchor } from '../utils/anchorNav';

/**
 * Прокрутка к якорю из адреса — то, чего браузер здесь сделать не может.
 *
 * Родная обработка `#…` разбирает адрес один раз, при загрузке документа, а
 * читальня — SPA: текст главы приезжает сетевым ответом уже после, и к моменту
 * разбора искомой секции в документе нет. Поэтому якорь ищется здесь, и —
 * второе следствие того же — не только на смену хэша, но и на смену
 * содержимого: `contentKey` это содержимое и называет.
 *
 * Только для входящих ссылок — открытых из письма или из выдачи поиска.
 * Якоря, нажатые здесь же (маркер полосы, строка оглавления, плавающий док),
 * прокручивают себя сами и правят адрес через `markAddress`: хэш при
 * повторном нажатии тот же самый, и одной сменой адреса второго прыжка не
 * сделать.
 */
export function useHashAnchor(contentKey: unknown): void {
  const { hash } = useLocation();

  useEffect(() => {
    if (!hash) return;
    // Хэш может указывать на полосу, которой в этой главе нет: ссылка собрана
    // руками или диапазон главы с тех пор изменился. Молчание уместнее ошибки,
    // поэтому неудача якоря здесь и остаётся неудачей.
    jumpToAnchor(hash.slice(1));
  }, [hash, contentKey]);
}
