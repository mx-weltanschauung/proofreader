/**
 * Что читальня умеет показать о себе сама.
 *
 * Поля «экран» здесь нет намеренно: экран — это множество выносок,
 * смонтированных прямо сейчас. Орган переехал на другую страницу — подсказка
 * переехала с ним, и править нечего.
 */
export type HintId =
  | 'page-numbers'
  | 'reading-settings'
  | 'scroll-dock-chapter'
  | 'outline-depth'
  | 'volume-scale'
  | 'front-matter'
  | 'download'
  | 'toc-drawer';

export interface HintDef {
  id: HintId;
  /** Больше — раньше. Сравнивается только среди выносок с видимым якорем. */
  priority: number;
  /** Одна фраза в пузырьке. Длиннее двух строк в 280px не влезает. */
  text: string;
}

