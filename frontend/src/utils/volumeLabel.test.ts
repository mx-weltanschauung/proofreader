describe('plural', () => {
  // Тома: наивная формула «n < 5 ? тома : томов» врёт на 21 (даёт «21 томов»
  // вместо «21 том») и на 43 (даёт «43 томов» вместо «43 тома») — оба случая
  // из целевого состояния плана (шкаф на 43 корешка) проверяются явно.
  it.each([
    [1, '1 том'],
    [3, '3 тома'],
    [5, '5 томов'],
    [11, '11 томов'],
    [21, '21 том'],
    [43, '43 тома'],
  ])('том %i -> %s', (n, expected) => {
    expect(plural(n, ['том', 'тома', 'томов'])).toBe(expected);
  });
});

function tops(...pairs: [string, number][]): TopChapter[] {
  const total = pairs.reduce((sum, [, pages]) => sum + pages, 0);
  return pairs.map(([title, pages]) => ({ title, pages, share: pages / total }));
}

