describe('firstSentence', () => {
  // Настоящий заголовок главы тома 3 — 165 знаков. Корешок отводит подписи
  // 150 пикселей и обрезает её посреди перечня философов; план требует, чтобы
  // на третьем томе читалось «Немецкая идеология».
  it('обрезает титульное описание до названия работы', () => {
    expect(
      firstSentence(
        'Немецкая идеология. Критика новейшей немецкой философии в лице её ' +
          'представителей Фейербаха, Б. Бауэра и Штирнера и немецкого социализма ' +
          'в лице его различных пророков',
      ),
    ).toBe('Немецкая идеология');
  });

  it.each([['Положение рабочего класса в Англии'], ['Статьи из «NRhZ»'], ['Тезисы о Фейербахе']])(
    'заголовок без точки оставляет целым: %s',
    (input) => {
      expect(firstSentence(input)).toBe(input);
    },
  );

  // Точка после одной буквы — сокращение, а не конец предложения.
  it.each([
    ['Современное состояние английской армии, ее тактика и т. д.'],
    ['Б. Бауэр и первоначальное христианство'],
  ])('не принимает сокращение за конец предложения: %s', (input) => {
    expect(firstSentence(input)).toBe(input);
  });

  // Обрезав по точке внутри кавычек, подпись осталась бы с открытой кавычкой.
  it('не режет по точке внутри названия в кавычках', () => {
    const title = 'Извещение о выходе «Neue Rheinische Zeitung. Politisch-okonomische Revue»';
    expect(firstSentence(title)).toBe(title);
  });

  // Заголовки газетных статей перечисляют темы через тире, иногда без
  // пробела перед ним. Первая тема — и есть название.
  it('режет по точке перед тире', () => {
    expect(firstSentence('Выборы в Англии.—Тори и виги')).toBe('Выборы в Англии');
  });

  it('снимает точку в конце заголовка', () => {
    expect(firstSentence('Заявление. 17 марта 1842 г.')).toBe('Заявление');
  });

  // Письма ПСС Ленина (тома 46—52, 55) заведены главами верхнего уровня с
  // порядковым номером впереди: «232.» удовлетворяет требованию в два
  // незнаковых знака перед точкой, и без проверки на букву подпись вырождалась
  // в голое число.
  it.each([
    ['232. М. Н. ЛЯДОВУ. 10 ноября', '232. М. Н. ЛЯДОВУ'],
    ['11. Л. Н. ПОТРЕСОВУ', '11. Л. Н. ПОТРЕСОВУ'],
  ])('не режет по номеру письма: %s -> %s', (input, expected) => {
    expect(firstSentence(input)).toBe(expected);
  });

  // Заголовок, начинающийся с настоящего предложения (буква есть в
  // отрезаемой голове), режется как прежде — номер письма ничего не меняет
  // в обычном случае.
  it('заголовок с настоящим предложением режется как прежде', () => {
    expect(firstSentence('Заявление. 17 марта 1842 г.')).toBe('Заявление');
  });

  // Заглавие ленинского тома 1 — 122 знака, и на корешок оно ехало целиком:
  // конец предложения искался только по точке. Вопросительный знак — такой же
  // конец, но, в отличие от точки, он часть заглавия и остаётся.
  it.each([
    [
      'ЧТО ТАКОЕ «ДРУЗЬЯ НАРОДА» И КАК ОНИ ВОЮЮТ ПРОТИВ СОЦИАЛ-ДЕМОКРАТОВ? ' +
        '(Ответ на статьи «Русского Богатства» против марксистов)',
      'ЧТО ТАКОЕ «ДРУЗЬЯ НАРОДА» И КАК ОНИ ВОЮЮТ ПРОТИВ СОЦИАЛ-ДЕМОКРАТОВ?',
    ],
    ['ЧТО ДЕЛАТЬ? Наболевшие вопросы нашего движения', 'ЧТО ДЕЛАТЬ?'],
    ['ПОЖАЛЕЙТЕ ЖЕ РУССКИЙ ЯЗЫК! Заметка публициста', 'ПОЖАЛЕЙТЕ ЖЕ РУССКИЙ ЯЗЫК!'],
  ])('режет по вопросительному и восклицательному знаку: %s', (input, expected) => {
    expect(firstSentence(input)).toBe(expected);
  });

  // Вопросительный знак в конце — уже конец заглавия, резать нечего, и знак
  // остаётся на месте (в отличие от точки, которую съедает то же правило).
  it('не трогает заголовок, оканчивающийся вопросительным знаком', () => {
    const title = 'В ХВОСТЕ У МОНАРХИЧЕСКОЙ БУРЖУАЗИИ ИЛИ ВО ГЛАВЕ ПРОЛЕТАРИАТА?';
    expect(firstSentence(title)).toBe(title);
  });

  // Многоточие — не конец предложения: «...» в середине заглавия начинается
  // с точки, за которой идёт точка, а не пробел.
  it('не режет по многоточию', () => {
    const title = '«УСЛЫШИШЬ СУД ГЛУПЦА»... Заметки публициста';
    expect(firstSentence(title)).toBe(title);
  });

  // Точка в «с.-д.» проходит требование в два незнаковых знака («-д.») и до
  // сих пор резала заглавие посреди скобки, оставляя её незакрытой. Скобки
  // считаются так же, как кавычки.
  it('не режет по точке внутри скобок', () => {
    const title = '«УСЛЫШИШЬ СУД ГЛУПЦА»... (Из заметок с.-д. публициста)';
    expect(firstSentence(title)).toBe(title);
  });
});

