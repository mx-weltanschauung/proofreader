describe('isDominant', () => {
  // Ленинский том 11: объём неаппаратных работ 385 страниц, «Две тактики»
  // — 131 (доля 0.340), вторая работа — 19 (доля 0.049). Доли не хватает до
  // половины, но хватает до трети, а 131 ≥ 2×19 — работает именно вторая
  // половина правила, а не первая (в отличие от старой фикстуры с одними
  // двумя работами, где доля первой всегда получалась выше 0.5 и вторая
  // половина правила ни разу не проверялась).
  it('принимает крупную работу, явно превосходящую вторую', () => {
    expect(isDominant(tops(['ДВЕ ТАКТИКИ', 131], ['второстепенная', 19], ['прочее', 235]))).toBe(
      true,
    );
  });

  // Ленинский том 1: 0.42 — больше, чем у тома 11, — но вторая работа почти
  // равна первой. Назвать том только первой значит умолчать о половине.
  // Третья пара — остаток тома: без него доля первой из двух подсчиталась бы
  // от их же суммы и вышла бы за половину сама по себе, что не отражает
  // реальный том (там 0.42 и 0.35 — от полного объёма).
  it('отклоняет работу, у которой вторая почти равна', () => {
    expect(
      isDominant(
        tops(
          ['ЧТО ТАКОЕ «ДРУЗЬЯ НАРОДА»', 222],
          ['ЭКОНОМИЧЕСКОЕ СОДЕРЖАНИЕ', 185],
          ['прочее', 122],
        ),
      ),
    ).toBe(false);
  });

  // Плехановский том 5: две трети тома одной работой, но до двукратного
  // превосходства не хватает девяти страниц. Половина тома решает сама.
  it('принимает работу на половину тома без двукратного превосходства', () => {
    expect(isDominant(tops(['Н. Г. Чернышевский', 239], ['прочее', 124]))).toBe(true);
  });

  it('отклоняет мелкую работу, даже если вторая много меньше', () => {
    expect(isDominant(tops(['мелкая', 60], ['ещё мельче', 10], ['и ещё', 400]))).toBe(false);
  });

  it('на пустом списке отвечает нет', () => {
    expect(isDominant([])).toBe(false);
  });
});

describe('volumeLabel', () => {
  it('ручная подпись бьёт всё остальное', () => {
    expect(
      volumeLabel(
        volume({
          shelf_label: '1893—1894',
          top_chapters: tops(['МАТЕРИАЛИЗМ И ЭМПИРИОКРИТИЦИЗМ', 384], ['прочее', 20]),
          chapters_total: 6,
        }),
      ),
    ).toBe('1893—1894');
  });

  it('ручная подпись из одних пробелов не считается подписью', () => {
    expect(
      volumeLabel(
        volume({ shelf_label: '   ', top_chapters: tops(['ЧТО ДЕЛАТЬ?', 190], ['прочее', 20]) }),
      ),
    ).toBe('ЧТО ДЕЛАТЬ?');
  });

  it('доминирующая работа даёт подпись одной работой', () => {
    expect(
      volumeLabel(volume({ top_chapters: tops(['Немецкая идеология', 538], ['прочее', 48]) })),
    ).toBe('Немецкая идеология');
  });

  // Том 2 Маркса и Энгельса — 598 страниц, «Положение рабочего класса в
  // Англии» и «Святое семейство» дают доли 0.48 и 0.38; третья пара тут же
  // держит долю первой работы на этом настоящем уровне, а не на 0.56, в
  // какие её раздула бы сумма одних этих двух работ.
  it('без доминанты перечисляет две первые работы', () => {
    expect(
      volumeLabel(
        volume({
          top_chapters: tops(
            ['Положение рабочего класса в Англии', 287],
            ['Святое семейство', 228],
            ['прочее', 85],
          ),
        }),
      ),
    ).toBe('Положение рабочего класса в Англии · Святое семейство');
  });

  it('единственную работу называет ею самой', () => {
    expect(volumeLabel(volume({ top_chapters: tops(['Искусство и литература', 349]) }))).toBe(
      'Искусство и литература',
    );
  });

  it('без работ, но с главами считает главы', () => {
    expect(volumeLabel(volume({ top_chapters: [], chapters_total: 72 }))).toBe('72 работы');
  });

  it('без глав вовсе молчит', () => {
    expect(volumeLabel(volume({ top_chapters: [], chapters_total: 0 }))).toBe('');
  });

  it('в подписи режет выноску и авторский префикс', () => {
    expect(
      volumeLabel(
        volume({
          top_chapters: tops(['К. Маркс. Лорд Пальмерстон.............', 300], ['прочее', 20]),
        }),
      ),
    ).toBe('Лорд Пальмерстон');
  });
});

describe('volumeLabelParts', () => {
  // Склеенная подпись разгонялась до 194 знаков и гасла посреди первой
  // работы. Разобранная обратно на работы, она ложится по строке на каждую, и
  // гаснуть становится нечему: медиана заглавия одной работы — 43 знака.
  it('отдаёт две работы порознь, а не склейкой', () => {
    expect(
      volumeLabelParts(
        volume({
          top_chapters: tops(
            ['Положение рабочего класса в Англии', 287],
            ['Святое семейство', 228],
            ['прочее', 85],
          ),
        }),
      ),
    ).toEqual(['Положение рабочего класса в Англии', 'Святое семейство']);
  });

  it('доминирующую работу отдаёт одной строкой', () => {
    expect(
      volumeLabelParts(volume({ top_chapters: tops(['Немецкая идеология', 538], ['прочее', 48]) })),
    ).toEqual(['Немецкая идеология']);
  });

  it('ручную подпись отдаёт как есть, одной строкой', () => {
    expect(
      volumeLabelParts(
        volume({
          shelf_label: '1893—1894',
          top_chapters: tops(['МАТЕРИАЛИЗМ И ЭМПИРИОКРИТИЦИЗМ', 384], ['прочее', 20]),
        }),
      ),
    ).toEqual(['1893—1894']);
  });

  it('без работ, но с главами считает главы', () => {
    expect(volumeLabelParts(volume({ top_chapters: [], chapters_total: 72 }))).toEqual([
      '72 работы',
    ]);
  });

  it('без глав вовсе отдаёт пусто', () => {
    expect(volumeLabelParts(volume({ top_chapters: [], chapters_total: 0 }))).toEqual([]);
  });

  // Подпись на корешке и подпись для чтения с экрана обязаны говорить одно и
  // то же: aria-label собирается из volumeLabel, строки — из частей.
  it('склеенные части дают ровно volumeLabel', () => {
    const v = volume({
      top_chapters: tops(['Что делать?', 190], ['Аграрный вопрос', 150], ['прочее', 60]),
    });
    expect(volumeLabelParts(v).join(' · ')).toBe(volumeLabel(v));
  });
});

describe('spineNumberParts', () => {
  // «26·III» одной строкой при кегле 24px занимает 65.4px (замер настоящим
  // Literata), а колонка клейма — 41.6px: номер вылезал влево и
  // перечёркивался задней стенкой. Разобранный на ярусы, он занимает 27.9px —
  // ровно столько же, сколько обычное двузначное «55».
  it('отделяет часть от номера', () => {
    expect(spineNumberParts(volume({ volume_number: 26, volume_part: 'III' }))).toEqual({
      number: '26',
      part: 'III',
    });
  });

  it('у тома без частей части не выдумывает', () => {
    expect(spineNumberParts(volume({ volume_number: 3 }))).toEqual({ number: '3' });
  });

  // Справочный том собрания Маркса и Энгельса номера не несёт вовсе.
  it('том без номера помечает «ук»', () => {
    expect(spineNumberParts(volume({ volume_number: undefined }))).toEqual({ number: 'ук' });
  });

  // Клеймо на книге и номер в карточке обязаны говорить одно и то же.
  it('склеенные ярусы дают ровно spineNumber', () => {
    const v = volume({ volume_number: 25, volume_part: 'II' });
    const { number, part } = spineNumberParts(v);
    expect(part ? `${number}·${part}` : number).toBe(spineNumber(v));
  });
});

describe('isMostlyCaps', () => {
  // 42 подписи из 95 приезжают из содержания сплошным капсом. Приводить их к
  // строчным нельзя — «Х СЪЕЗД РКП(б)» превратится в кашу, — поэтому капс
  // опознаётся и гасится кеглем, а сам текст остаётся нетронутым.
  it('узнаёт заголовок из содержания', () => {
    expect(isMostlyCaps('ЧТО ТАКОЕ «ДРУЗЬЯ НАРОДА»')).toBe(true);
  });

  it('обычную строчную подпись капсом не считает', () => {
    expect(isMostlyCaps('Положение рабочего класса в Англии')).toBe(false);
  });

  // «III СЪЕЗД РСДРП 12— 27 апреля (25 апреля — 10 мая) 1905 г» — капса
  // больше половины, но строчного хвоста хватает, чтобы строка читалась
  // обычной. Гасить её кеглем не за что.
  it('смешанную строку капсом не считает', () => {
    expect(isMostlyCaps('III СЪЕЗД РСДРП 12— 27 апреля (25 апреля — 10 мая) 1905 г')).toBe(false);
  });

  // Цифры и знаки препинания регистра не имеют и в счёт идти не должны:
  // «1893—1894» иначе прошло бы как капс (ноль строчных из нуля букв).
  it('строку без букв капсом не считает', () => {
    expect(isMostlyCaps('1893—1894')).toBe(false);
  });

  it('пустую строку капсом не считает', () => {
    expect(isMostlyCaps('')).toBe(false);
  });
});

describe('chapterLabel', () => {
  it('оставляет первое предложение и срезает выноску', () => {
    expect(chapterLabel('МАТЕРИАЛИЗМ И ЭМПИРИОКРИТИЦИЗМ. Критические заметки.......')).toBe(
      'МАТЕРИАЛИЗМ И ЭМПИРИОКРИТИЦИЗМ',
    );
  });

  // Регистр не трогается: приведение сломало бы римские цифры и аббревиатуры.
  it('не трогает регистр', () => {
    expect(chapterLabel('Х СЪЕЗД РКП(б)')).toBe('Х СЪЕЗД РКП(б)');
  });

  // Обе обрезки разом на самом длинном заглавии живой базы: 122 знака ужимаются
  // до 66. Порядок важен — подзаголовок ищется уже в первом предложении.
  it('режет и по вопросительному знаку, и по подзаголовку', () => {
    expect(
      chapterLabel(
        'ЧТО ТАКОЕ «ДРУЗЬЯ НАРОДА» И КАК ОНИ ВОЮЮТ ПРОТИВ СОЦИАЛ-ДЕМОКРАТОВ? ' +
          '(Ответ на статьи «Русского Богатства» против марксистов)',
      ),
    ).toBe('ЧТО ТАКОЕ «ДРУЗЬЯ НАРОДА» И КАК ОНИ ВОЮЮТ ПРОТИВ СОЦИАЛ-ДЕМОКРАТОВ?');
  });

  // Скобка, до которой firstSentence прежде дорезал по «с.-д.», теперь
  // отваливается целиком — от заглавия остаётся название статьи.
  it('срезает скобку, внутри которой есть сокращение с точкой', () => {
    expect(chapterLabel('«УСЛЫШИШЬ СУД ГЛУПЦА»... (Из заметок с.-д. публициста)')).toBe(
      '«УСЛЫШИШЬ СУД ГЛУПЦА»...',
    );
  });

  // Заглавие, где подзаголовок отделён точкой, а скобка стоит в конце: сперва
  // отваливается всё после точки, скобка уезжает вместе с ним.
  it('срезает подзаголовок, начинающийся после точки', () => {
    expect(
      chapterLabel('EIN SCHRITT VORWÄRTS, ZWEI SCHRITTE RÜCKWÄRTS. Eine Abwehr von N. Lenin (ШАГ)'),
    ).toBe('EIN SCHRITT VORWÄRTS, ZWEI SCHRITTE RÜCKWÄRTS');
  });
});

describe('spineNumber', () => {
  it('обычный том — просто номер', () => {
    expect(spineNumber(volume({ volume_number: 3 }))).toBe('3');
  });

  // Тома 25 и 26 в этом издании выходили в двух книгах.
  it('том из двух книг — номер с частью', () => {
    expect(spineNumber(volume({ volume_number: 25, volume_part: 'I' }))).toBe('25·I');
  });

  it('работа без номера тома — «ук»', () => {
    expect(spineNumber(volume({ volume_number: undefined }))).toBe('ук');
  });
});
