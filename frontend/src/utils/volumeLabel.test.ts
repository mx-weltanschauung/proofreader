function volume(over: Partial<VolumeSummary>): VolumeSummary {
  return {
    id: 1,
    title: 'Том',
    author: '',
    language: '',
    country: '',
    file_path: '',
    status: 'draft',
    page_offset: 0,
    owner_id: 1,
    created_at: '',
    updated_at: '',
    pages_total: 600,
    pages_by_status: {},
    chapters_total: 0,
    ...over,
  } as VolumeSummary;
}

