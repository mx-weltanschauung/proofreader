import type { PageStatus } from '../types';

/**
 * Подпись статуса для читателя понятия.
 *
 * Молчит ровно об одном значении — `вычитана`: там текст сверен человеком и
 * добавить нечего. Про всё остальное сказать надо, иначе исследователь примет
 * сырой OCR за текст Маркса. Значения статуса — русскоязычный enum, менять их
 * строки нельзя, поэтому подпись получается заменой подчёркиваний.
 */
export function readerStatusLabel(status: PageStatus): string {
  if (status === 'вычитана') return '';
  return status.replace(/_/g, ' ');
}

/**
 * Подпись статуса для карточки страницы: называет значение всегда, включая
 * `вычитана` — в отличие от `readerStatusLabel`, у которой молчание для этого
 * статуса осмысленно только в контексте читателя понятия (см. её комментарий).
 * Значения статуса — русскоязычный enum, менять их строки нельзя, поэтому
 * подпись получается заменой подчёркиваний.
 */
export function pageStatusLabel(status: PageStatus): string {
  return status.replace(/_/g, ' ');
}
