import { describe, it, expect } from 'vitest';
import { quoteKey, quoteTail } from './quoteKey';

describe('quoteKey', () => {
  it('режет до первого префикса, встречающегося на полосе один раз', () => {
    const page = 'Мы идём тесной кучкой. Мы идём вперёд и вперёд.';
    expect(quoteKey('Мы идём вперёд и вперёд.', page)).toBe('Мы идём вперёд');
  });

  it('растёт по словам, а не по знакам', () => {
    const page = 'абвгд еёжзи. абвгд клмно.';
    expect(quoteKey('абвгд клмно.', page)).toBe('абвгд клмно.');
  });

  it('уникального префикса нет — отдаёт выделение целиком', () => {
    const page = 'строка повтора\nстрока повтора';
    expect(quoteKey('строка повтора', page)).toBe('строка повтора');
  });

  it('нормализует обе стороны одинаково', () => {
    expect(quoteKey('  первое\n слово  ', 'а первое слово б')).toBe('первое');
  });

  it('пустое выделение даёт пустой ключ', () => {
    expect(quoteKey('   ', 'что угодно')).toBe('');
  });
});

describe('quoteTail', () => {
  it('режет до первого суффикса, встречающегося на полосе один раз', () => {
    const page = 'Мы идём тесной кучкой, мы идём вперёд кучкой';
    expect(quoteTail('мы идём вперёд кучкой', page)).toBe('вперёд кучкой');
  });

  it('растёт по словам влево, а не по знакам', () => {
    const page = 'абвгд клмно. еёжзи клмно.';
    expect(quoteTail('еёжзи клмно.', page)).toBe('еёжзи клмно.');
  });

  it('уникального суффикса нет — отдаёт хвост целиком', () => {
    const page = 'строка повтора строка повтора';
    expect(quoteTail('строка повтора', page)).toBe('строка повтора');
  });

  it('нормализует обе стороны одинаково', () => {
    expect(quoteTail('  первое\n слово  ', 'а первое слово б')).toBe('слово');
  });

  it('пустой хвост даёт пустой якорь', () => {
    expect(quoteTail('   ', 'что угодно')).toBe('');
  });
});
