import type { TopChapter, VolumeSummary } from '../types';
import { AUTHOR_PREFIX } from './chapterAuthor';

export function stripAuthorPrefix(title: string): string {
  return title.replace(AUTHOR_PREFIX, '');
}

// Конец предложения: точка, вопросительный или восклицательный знак, перед
// которым стоят два непробельных знака, а после — пробел, конец строки или
// тире. Двух знаков требуем, чтобы не принять за конец предложения сокращение:
// перед точкой в «Б. Бауэра», «и т. д.», «1846 г.» стоит одна буква,
// отделённая пробелом. Многоточие правило не ловит само собой: перед второй
// точкой стоит первая, а она из `[^\s.]` исключена.
const SENTENCE_END = /[^\s.]{2}[.?!](?=\s|$|[—–])/g;

function count(haystack: string, needle: string): number {
  return haystack.split(needle).length - 1;
}

/**
 * Первое предложение заголовка.
 *
 * В базе у главы лежит полное титульное описание работы: у «Немецкой
 * идеологии» это 165 знаков вместе с перечнем критикуемых философов. На
 * корешке столько не помещается, и CSS обрезает подпись посреди фразы —
 * читается обрывок. На переплёте книги стоит первое предложение заглавия,
 * его и берём.
 */
export function firstSentence(title: string): string {
  for (const match of title.matchAll(SENTENCE_END)) {
    // matchAll над регуляркой с `g` не переносит lastIndex наружу: он ведёт
    // свой экземпляр. Индекс знака — последний знак совпадения.
    const at = (match.index ?? 0) + match[0].length - 1;
    // Точка отделяет подзаголовок и в заглавие не входит, а вопросительный и
    // восклицательный знаки — часть самого заглавия: «ЧТО ДЕЛАТЬ?» без знака
    // перестаёт быть вопросом.
    const head = title.slice(0, title[at] === '.' ? at : at + 1);
    // Точка внутри кавычек — часть названия газеты («Neue Rheinische
    // Zeitung. Politisch-okonomische Revue»), а не конец предложения:
    // обрезав по ней, мы оставили бы открытую кавычку. Скобки считаются по
    // той же причине: в «(Из заметок с.-д. публициста)» точка сокращения
    // проходит требование в два незнаковых знака («-д.»), и обрезка по ней
    // оставляла подпись с открытой скобкой.
    if (count(head, '«') !== count(head, '»')) continue;
    if (count(head, '(') !== count(head, ')')) continue;
    // Письма ПСС Ленина заведены главами верхнего уровня с порядковым
    // номером впереди: «232. М. Н. ЛЯДОВУ. 10 ноября». Два незнаковых знака
    // перед точкой требование не спасает — «32.» тоже подходит под него, —
    // и без буквы в отрезаемой голове подпись вырождается в голое число.
    // Пропускаем такую точку и ищем следующую.
    if (!/\p{L}/u.test(head)) continue;
    return head;
  }
  return title;
}

/**
 * Русское число + существительное с правильным склонением. `forms` — три
 * формы в порядке [именительный ед., родительный ед., родительный мн.],
 * например `['том', 'тома', 'томов']` или `['работа', 'работы', 'работ']`.
 */
export function plural(n: number, forms: [string, string, string]): string {
  return `${n} ${nounForm(n, forms)}`;
}

/**
 * Одна форма существительного без числа перед ней. Нужна там, где число уже
 * написано в другом виде: «45 из 55 томов» (склонение ведёт знаменатель) или
 * «27 719 страниц» (число разделено на разряды и в него не подставишь).
 */
export function nounForm(n: number, forms: [string, string, string]): string {
  const hundred = n % 100;
  const ten = n % 10;
  if (hundred >= 11 && hundred <= 14) return forms[2];
  if (ten === 1) return forms[0];
  if (ten >= 2 && ten <= 4) return forms[1];
  return forms[2];
}

export function worksPlural(n: number): string {
  return plural(n, ['работа', 'работы', 'работ']);
}

/**
 * Доля, при которой работа называет том сама, без оглядки на соседей: половина
 * тома. Плехановский том 5 — 239 страниц «Н. Г. Чернышевского» из 363 — до
 * двукратного превосходства над второй работой не дотягивает девяти страниц,
 * но том всё равно её и есть.
 */
export const DOMINANT_SHARE = 0.5;

/**
 * Доля, при которой работа называет том, если вдобавок явно крупнее второй.
 * Порога по доле самого по себе мало: ленинский том 1 проходит его с 0.42, но
 * вторая работа там 0.35 — назвать том только первой значит умолчать о
 * половине. Ленинский том 11 проходит с меньшим 0.34, и там это честно:
 * вторая работа вшестеро мельче.
 */
export const STRONG_SHARE = 0.3;

/** Хвост из точек и пробелов: выноска строки содержания, а не часть заглавия. */
const TRAILING_LEADERS = /[.\s…]{4,}$/;

/**
 * Срезает точечную выноску, приехавшую из содержания: «III СЪЕЗД РСДРП
 * 1905 г.............». Порог в четыре знака, а не в три, — чтобы не съесть
 * настоящее многоточие в конце заглавия.
 */
export function stripLeaders(title: string): string {
  return title.replace(TRAILING_LEADERS, '');
}

/**
 * Пояснительный подзаголовок в скобках в конце заглавия: «(Кризис в нашей
 * партии)», «(Популярный очерк)», «(Ответ на статьи «Русского Богатства»…)».
 * На корешке он съедает до половины подписи, а на переплёте книги его и не
 * ставят — там стоит главное заглавие.
 *
 * Три условия разом, и каждое отсекает свой ложный случай на живой базе:
 * скобка стоит в самом конце («VI (ПРАЖСКАЯ) КОНФЕРЕНЦИЯ» цела), перед ней
 * пробел («ПРОЕКТ ПРОГРАММЫ РКП(б)» цел), внутри — прописная буква. Последнее
 * условие и есть содержательное: скобка со строчной не поясняет заглавие, а
 * различает работы — «Дебаты шестого рейнского ландтага (статья первая)» и
 * «(статья третья)» без неё слились бы в одну подпись.
 */
const TRAILING_SUBTITLE = /\s\(\p{Lu}[^()]*\)$/u;

export function stripSubtitle(title: string): string {
  return title.replace(TRAILING_SUBTITLE, '');
}

/**
 * Заглавие работы в том виде, в каком оно годится для корешка и карточки.
 * Регистр не трогается намеренно: заголовки приезжают из содержания капсом, и
 * приведение превратило бы «Х СЪЕЗД РКП(б)» в «х съезд ркп(б)».
 */
export function chapterLabel(title: string): string {
  return stripSubtitle(firstSentence(stripLeaders(stripAuthorPrefix(title))));
}

/**
 * Называется ли том одной работой. Обе половины правила нужны: доля отвечает
 * за величину работы, превосходство над второй — за то, что она в томе одна
 * такая.
 */
export function isDominant(top: TopChapter[]): boolean {
  if (top.length === 0) return false;
  const [first, second] = top;
  if (first.share >= DOMINANT_SHARE) return true;
  return first.share >= STRONG_SHARE && first.pages >= 2 * (second?.pages ?? 0);
}

/**
 * Подпись на корешке, разобранная на работы: по строке на каждую.
 *
 * Строк не больше двух. Склеенная в одну строку через « · », эта же подпись
 * разгонялась до 194 знаков при ширине корешка в 45 и гасла посреди первой
 * работы — то есть первая работа не читалась ради второй, которая не
 * читалась тоже. Порознь каждая ложится в свою строку: медиана заглавия одной
 * работы по корпусу — 43 знака, три четверти короче 62.
 *
 * Ручная подпись бьёт любой вывод: она для того и заведена.
 */
export function volumeLabelParts(volume: VolumeSummary): string[] {
  const manual = (volume.shelf_label ?? '').trim();
  if (manual) return [manual];

  const top = volume.top_chapters ?? [];
  if (isDominant(top)) return [chapterLabel(top[0].title)];
  // Пара работ — основная подпись, а не запасной путь: в ленинском томе
  // шесть десятков работ, и ни одна не задаёт его целиком.
  if (top.length >= 2) return [chapterLabel(top[0].title), chapterLabel(top[1].title)];
  if (top.length === 1) return [chapterLabel(top[0].title)];
  if (volume.chapters_total > 0) return [worksPlural(volume.chapters_total)];
  return [];
}

/**
 * Подпись на корешке одной строкой. Нужна там, где строк нет: `aria-label`
 * книги и заголовок карточки читаются подряд, а не раскладываются.
 */
export function volumeLabel(volume: VolumeSummary): string {
  return volumeLabelParts(volume).join(' · ');
}

/**
 * Доля прописных, при которой строка считается набранной капсом.
 * Не единица: «Х СЪЕЗД РКП(б)» и «VIII СЪЕЗД РКП (б)» несут строчную букву
 * внутри аббревиатуры и капсом быть не перестают.
 */
const MOSTLY_CAPS_SHARE = 0.8;

/**
 * Набрана ли строка капсом.
 *
 * Сорок две подписи из девяноста пяти приезжают из содержания сплошными
 * прописными. Привести их к строчным нельзя: это сломает римские цифры и
 * аббревиатуры — «Х СЪЕЗД РКП(б)» станет «х съезд ркп(б)». Поэтому текст
 * остаётся нетронутым, а опознанный капс гасится кеглем и разрядкой, чтобы
 * его оптический вес сравнялся с весом обычной строки.
 *
 * Считаются только буквы: цифры и знаки регистра не имеют, и без этого
 * условия ручная подпись «1893—1894» прошла бы как капс — ноль строчных из
 * ноля букв.
 */
export function isMostlyCaps(text: string): boolean {
  const letters = [...text].filter((ch) => /\p{L}/u.test(ch));
  const upper = letters.filter((ch) => ch === ch.toUpperCase()).length;
  // `upper > 0` — не украшение перед делением, а само условие «букв нет»:
  // доля считается умножением, и без него «1893—1894» дало бы 0 >= 0, то есть
  // капс из строки, в которой нет ни одной буквы.
  return upper > 0 && upper >= letters.length * MOSTLY_CAPS_SHARE;
}

/**
 * Номер на корешке, разобранный на ярусы: сам номер и часть, если том вышел
 * в нескольких книгах. В корпусе таких четыре, все у Маркса и Энгельса —
 * 25·II, 26·I, 26·II, 26·III, — и часть у них римская.
 *
 * Разбор нужен клейму на книге, где номер набран в 24px: «26·III» одной
 * строкой занимает при этом кегле 65.4px (замер настоящим Literata), а
 * колонка клейма — 41.6px, и номер вылезал из неё влево, перечёркиваясь
 * задней стенкой. Расширять колонку ради четырёх томов значило бы отнять
 * ширину у подписи всех девяноста пяти. Поставленная под номер вторым ярусом
 * и мельче, часть укладывается в 27.9px — ровно столько же занимает обычное
 * двузначное «55».
 */
export function spineNumberParts(volume: VolumeSummary): { number: string; part?: string } {
  if (volume.volume_number === undefined) return { number: 'ук' };
  const number = `${volume.volume_number}`;
  return volume.volume_part ? { number, part: volume.volume_part } : { number };
}

/**
 * Номер на корешке одной строкой. Нужен там, где ярусов нет: `aria-label`
 * книги и заголовок карточки читаются подряд.
 */
export function spineNumber(volume: VolumeSummary): string {
  const { number, part } = spineNumberParts(volume);
  return part ? `${number}·${part}` : number;
}
