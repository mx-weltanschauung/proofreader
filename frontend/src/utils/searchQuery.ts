/**
 * Пол длины поискового запроса. Повторяет `minQueryRunes` на сервере
 * (`internal/api/search_query.go`): клиент отказывает заранее, чтобы читатель
 * увидел причину, а не пустую выдачу, но решающая проверка остаётся на
 * сервере — по прямому адресу `/search?q=и` форма не участвует вовсе.
 */
export const MIN_QUERY_LENGTH = 2;

/** Те же слова, что в ответе сервера: читатель не должен получать две разные
 *  формулировки одного отказа в зависимости от того, набрал он запрос в форме
 *  или пришёл по ссылке. */
export const TOO_SHORT_MESSAGE = 'Слишком короткий запрос: не меньше двух символов';

/** Обрезка краёв и схлопывание пробелов — то же, что делает сервер перед
 *  разбором. Клиент считает длину по этой же форме, иначе «  и  » прошло бы
 *  порог на клиенте и получило отказ сервером. */
export function normalizeQuery(raw: string): string {
  return raw.trim().replace(/\s+/g, ' ');
}

/**
 * Запрос короче пола. Длина считается в кодовых точках (`Array.from`), а не
 * в `.length`: у строки длина в единицах UTF-16, и суррогатная пара — один
 * знак — сошла бы за два.
 */
export function isTooShortQuery(raw: string): boolean {
  return Array.from(normalizeQuery(raw)).length < MIN_QUERY_LENGTH;
}
