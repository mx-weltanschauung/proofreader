/**
 * Раскладка полки: чем занят каждый её отрезок.
 *
 * Толщины у книги нет — все тома одной мерки (`--slab-height` в
 * VolumeShelf.css). Толщина по объёму тома тут была дважды и оба раза снята:
 * у стоящего корешка она отнимала колонки вертикального набора, и заглавие
 * тонкого тома обрывалось посреди слова; у лежащей книги она не отнимала
 * ничего, но ровный штабель читается лучше рваного. Объём тома читатель
 * узнаёт из карточки по наведению и со страницы самого тома.
 */

/** Всё, что нужно от тома, чтобы поставить его на полку. */
export interface Positioned {
  volume_number?: number;
  volume_part?: string;
}

/**
 * Место на полке: либо книга, либо пустое место с номером тома, которого в
 * читальне пока нет.
 */
export type ShelfSlot<T> = { kind: 'volume'; volume: T } | { kind: 'gap'; number: number };

/**
 * Место на полке после того, как пропуски названы словами: либо книга, либо
 * прогон отсутствующих томов одной полосой. Отдельного пустого места здесь
 * уже нет — `mergeGapRuns` не оставляет ни одного, и тип это говорит: иначе
 * разметке пришлось бы разбирать ветку, которой не бывает.
 */
export type WordedSlot<T> =
  | { kind: 'volume'; volume: T }
  | { kind: 'run'; from: number; to: number; count: number };

/**
 * Раскладывает тома собрания по местам, оставляя пустое место каждому
 * ненаписанному номеру: и внутри ряда (у Ленина нет томов 3 и 5), и в начале
 * (Плеханов начинается с пятого). Пустое место — не украшение, а тот же
 * факт, что и книга: собрание неполно, и видно, где именно.
 *
 * Хвост — номера после последнего залитого тома — выкладывается до
 * `volumesPlanned`, если план собрания известен. Иначе полка обрывается на
 * последней книге: длину брать неоткуда.
 *
 * Хвост обязан быть таким же, как дыра в середине: у Плеханова том 15
 * отсутствует ровно так же, как том 8, и разное обращение с ними читалось бы
 * как «здесь собрание кончилось» — а оно не кончилось.
 */
export function shelfSlots<T extends Positioned>(
  volumes: T[],
  volumesPlanned?: number,
): ShelfSlot<T>[] {
  const numbered = volumes.filter((v) => v.volume_number !== undefined);
  // Тома без номера на числовой оси места не имеют — ни своего, ни соседского,
  // — поэтому просто дожидаются конца полки.
  const unnumbered = volumes.filter((v) => v.volume_number === undefined);

  const ordered = [...numbered].sort(
    (a, b) =>
      a.volume_number! - b.volume_number! ||
      (a.volume_part ?? '').localeCompare(b.volume_part ?? ''),
  );

  const slots: ShelfSlot<T>[] = [];
  // Начинаем с первого номера собрания, а не с первого залитого тома: пустое
  // начало полки — такой же пропуск, как и дыра в середине.
  let expected = 1;
  for (const volume of ordered) {
    for (; expected < volume.volume_number!; expected += 1) {
      slots.push({ kind: 'gap', number: expected });
    }
    slots.push({ kind: 'volume', volume });
    // Не expected += 1: у тома в двух книгах номер один на обе, и вторая книга
    // не должна открыть пустое место на месте собственного тома.
    expected = volume.volume_number! + 1;
  }

  // Справочный том (у собрания Маркса и Энгельса это указатель) идёт сразу за
  // последней книгой — до пустых мест, а не после них. Номера у него нет, но
  // сам он в читальне есть, а ненаписанных томов нет: отправить его в конец
  // значило бы поставить существующую книгу за границу несуществующих.
  for (const volume of unnumbered) {
    slots.push({ kind: 'volume', volume });
  }

  // Хвост до планового объёма. Условие `expected <=` заодно бережёт от плана,
  // который меньше числа залитых томов: он устарел или вписан неверно, и
  // выкинуть с полки настоящий том страшнее, чем показать её длиннее
  // объявленного.
  if (volumesPlanned !== undefined) {
    for (; expected <= volumesPlanned; expected += 1) {
      slots.push({ kind: 'gap', number: expected });
    }
  }

  return slots;
}

/**
 * Свёртывает каждый прогон пустых мест в одну подписанную полосу.
 *
 * Полоса называет диапазон словами («тома 12—15 ещё не сняты»), и это тот же
 * факт, что и цепочка пустых мест, — но сказанный, а не оставленный читателю
 * на подсчёт. Прежде отсутствующий том рисовался немой полосой задника, и на
 * неполном собрании такие полосы сливались в серую плиту: у Чернышевского
 * четыре тома на пятнадцать мест, у Плеханова четыре на двадцать четыре.
 *
 * Порога длины здесь нет намеренно, и это решение принято по рендеру, а не по
 * замыслу. Порог был — короткий пропуск оставался засечкой, потому что по
 * номерам соседних книг и так видно, какого тома нет. На живом корпусе
 * засечка в одно место оказалась culёй в три пикселя между двумя книгами и
 * читалась дефектом вёрстки, а не отсутствующим томом. Одна фраза вместо
 * культи стоит одной строки и говорит ровно то, что нужно.
 *
 * Начало и хвост собрания идут через то же правило, что и середина: у
 * Плеханова тома 1—4 отсутствуют ровно так же, как том 8, и разное обращение
 * с ними читалось бы как «отсюда собрание началось».
 */
export function mergeGapRuns<T>(slots: ShelfSlot<T>[]): WordedSlot<T>[] {
  const merged: WordedSlot<T>[] = [];
  let gaps: number[] = [];

  const flush = () => {
    if (gaps.length === 0) return;
    merged.push({
      kind: 'run',
      from: gaps[0],
      to: gaps[gaps.length - 1],
      count: gaps.length,
    });
    gaps = [];
  };

  for (const slot of slots) {
    if (slot.kind === 'gap') {
      gaps.push(slot.number);
      continue;
    }
    flush();
    merged.push(slot);
  }
  flush();

  return merged;
}

/** Сколько книг показывает свёрнутый штабель на узком экране. */
export const COLLAPSED_VOLUMES = 10;

/**
 * Сколько книг показывает свёрнутый штабель на широком экране — там, где его
 * об этом просят (главная; на странице собрания штабель идёт целиком).
 *
 * Больше узкого порога, и число выбрано под раскладку: на широком экране
 * штабель идёт в два столбца, и двенадцать книг ложатся ровным
 * прямоугольником шесть на шесть, тогда как десять оставили бы столбцы
 * разной высоты у собрания с пропусками.
 */
export const COLLAPSED_VOLUMES_WIDE = 12;

/**
 * Наименьшее число спрятанных книг, ради которого стоит заводить кнопку.
 * Ниже него сворачивание — работа читателю без выгоды: он жмёт «показать
 * все», чтобы увидеть ещё один том.
 */
const WORTH_HIDING = 3;

/**
 * Место, по которое свёрнутый штабель показывает книги: индекс первого
 * скрытого места, а если прятать нечего — длина всей раскладки.
 *
 * Счёт идёт по томам, а не по местам, и это здесь главное: у Плеханова между
 * пятым и четырнадцатым томом девять пустых мест, и штабель, свёрнутый по
 * первым десяти местам, показал бы одну книгу.
 *
 * Пустой хвост за последней показанной книгой уходит под кнопку вместе со
 * скрытыми томами — иначе свёрнутое собрание кончалось бы полосой пустых
 * мест, за которой якобы ничего нет.
 */
export function collapseAt<T>(
  slots: (ShelfSlot<T> | WordedSlot<T>)[],
  keep = COLLAPSED_VOLUMES,
): number {
  let seen = 0;
  let cut = slots.length;
  for (const [at, slot] of slots.entries()) {
    if (slot.kind !== 'volume') continue;
    seen += 1;
    if (seen === keep) cut = at + 1;
  }
  return seen >= keep + WORTH_HIDING ? cut : slots.length;
}

/**
 * Подпись свёрнутого прогона. Называет, каких томов нет, — единственное
 * место, где это сказано: счётчик собрания даёт итог «4 из 15», но не
 * перечисляет пропущенных.
 */
export function runCaption(from: number, to: number, count: number): string {
  return count === 1 ? `Том ${from} ещё не снят` : `Тома ${from}—${to} ещё не сняты`;
}
