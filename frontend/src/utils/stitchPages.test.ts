import { describe, expect, it } from 'vitest';
import { stitchPages } from './stitchPages';

const seam = {
  href: (n: number) => `/works/62/pages/${n}`,
  label: (n: number) => `Страница ${n}`,
};

/**
 * Текст всех абзацев куска html — по нему проверяется, что и куда уехало.
 * Маркеры номеров выброшены: это служебная разметка шва, а не текст книги.
 */
function paragraphs(html: string): string[] {
  const host = document.createElement('div');
  host.innerHTML = html;
  host.querySelectorAll('.page-marker').forEach((m) => m.remove());
  return Array.from(host.querySelectorAll('p')).map((p) => p.textContent?.trim() ?? '');
}

describe('stitchPages', () => {
  it('дописывает продолжение оборванной фразы в абзац предыдущей страницы', () => {
    const out = stitchPages(
      [
        { pageNumber: 176, html: '<p>то очевидно, что я</p>' },
        { pageNumber: 177, html: '<p>никогда бы не решился разойтись.</p>' },
      ],
      seam,
    );

    expect(paragraphs(out[0].html)).toEqual([
      'то очевидно, что я никогда бы не решился разойтись.',
    ]);
  });

  it('не склеивает законченную фразу с началом новой: печатный отступ тут неразличим', () => {
    const out = stitchPages(
      [
        { pageNumber: 176, html: '<p>к тем же выводам пришел и Каутский.</p>' },
        { pageNumber: 177, html: '<p>Плеханов, желая представить мое поведение…</p>' },
      ],
      seam,
    );

    expect(paragraphs(out[0].html)).toEqual(['к тем же выводам пришел и Каутский.']);
    expect(paragraphs(out[1].html)).toEqual(['Плеханов, желая представить мое поведение…']);
  });

  it('сращивает слово, разорванное переносом на границе полос', () => {
    const out = stitchPages(
      [
        { pageNumber: 26, html: '<p>речь шла про их «единственное» предста-</p>' },
        { pageNumber: 27, html: '<p>вительство еврейского пролетариата.</p>' },
      ],
      seam,
    );

    expect(paragraphs(out[0].html)).toEqual([
      'речь шла про их «единственное» представительство еврейского пролетариата.',
    ]);
  });

  it('сохраняет дефис составного слова: обе половины ходят по тексту сами по себе', () => {
    const out = stitchPages(
      [
        { pageNumber: 506, html: '<p>Спор с меньшевиками шел давно, и с оппортунистами тоже.</p>' },
        { pageNumber: 507, html: '<p>Борьба с оппортунистами-</p>' },
        { pageNumber: 508, html: '<p>меньшевиками только начиналась.</p>' },
      ],
      seam,
    );

    expect(paragraphs(out[1].html)).toEqual([
      'Борьба с оппортунистами-меньшевиками только начиналась.',
    ]);
  });

  it('оборачивает переехавший текст швом с маркером номера и якорем страницы', () => {
    const out = stitchPages(
      [
        { pageNumber: 176, html: '<p>то очевидно, что я</p>' },
        { pageNumber: 177, html: '<p>никогда бы не решился.</p><p>Второй абзац.</p>' },
      ],
      seam,
    );

    const host = document.createElement('div');
    host.innerHTML = out[0].html;
    const seamEl = host.querySelector('span.page-seam');

    expect(seamEl?.id).toBe('chapter-page-177');
    expect(seamEl?.classList.contains('chapter-page-section')).toBe(true);
    // Прыжок из оглавления переводит на секцию фокус: без tabindex шов его не
    // примет, и клавиатурный читатель потеряет позицию.
    expect(seamEl?.getAttribute('tabindex')).toBe('-1');
    expect(seamEl?.textContent).toBe('177никогда бы не решился.');

    const marker = seamEl?.querySelector('a.page-marker');
    expect(marker?.getAttribute('href')).toBe('/works/62/pages/177');
    expect(marker?.getAttribute('aria-label')).toBe('Страница 177');

    // Якорь и маркер теперь на шве — своих у секции быть не должно, иначе в
    // документе окажутся два элемента с одним id.
    expect(out[1].seamed).toBe(true);
    expect(paragraphs(out[1].html)).toEqual(['Второй абзац.']);
  });

  // Бэкенд больше не шлёт страницу целым документом — обёртку снимает сам
  // pkg/markdown (см. stitchPages.ts, DOCUMENT_CHROME). Фильтр остаётся
  // сторожем: один ответ от бэкенда, отставшего от master, вернул бы ровно
  // такую обёртку (DOCTYPE, <html>, <head> с <title> и <meta>), и без фильтра
  // браузер при вставке через innerHTML выбросил бы html/head/body, но
  // оставил <title> и <meta> — первым элементом страницы оказались бы они, а
  // не текст. Тест проверяет, что склейка переживёт такой ответ.
  it('не спотыкается о служебную обёртку документа вокруг страницы', () => {
    const wrap = (body: string) =>
      '<!DOCTYPE html>\n<html xmlns="http://www.w3.org/1999/xhtml">\n<head>\n' +
      '  <title></title>\n  <meta charset="utf-8" />\n</head>\n<body>\n\n' +
      body +
      '\n\n</body>\n</html>\n';

    const out = stitchPages(
      [
        { pageNumber: 176, html: wrap('<p>то очевидно, что я</p>') },
        { pageNumber: 177, html: wrap('<p>никогда бы не решился.</p>') },
      ],
      seam,
    );

    expect(paragraphs(out[0].html)).toEqual(['то очевидно, что я никогда бы не решился.']);
    expect(out[1].seamed).toBe(true);
  });

  it('не втягивает в абзац стихи, заголовки и списки', () => {
    const out = stitchPages(
      [
        { pageNumber: 10, html: '<p>и дальше он приводит строки</p>' },
        { pageNumber: 11, html: '<blockquote><p>гвоздь бы делать из этих людей</p></blockquote>' },
      ],
      seam,
    );

    expect(out[0].html).toBe('<p>и дальше он приводит строки</p>');
    expect(out[1].html).toBe('<blockquote><p>гвоздь бы делать из этих людей</p></blockquote>');
  });

  // Полоса из одного абзаца-продолжения уезжает в предыдущую целиком (в томе 62
  // таких 48). Текст при этом не прерывается, и следующая полоса продолжает
  // тот же самый абзац — иначе каждая такая страница обрывала бы цепочку.
  it('продолжает цепочку через полосу, уехавшую целиком', () => {
    const out = stitchPages(
      [
        { pageNumber: 20, html: '<p>мысль обрывается на</p>' },
        { pageNumber: 21, html: '<p>полуслове и тянется через всю полосу</p>' },
        { pageNumber: 22, html: '<p>до конца третьей.</p>' },
      ],
      seam,
    );

    expect(paragraphs(out[0].html)).toEqual([
      'мысль обрывается на полуслове и тянется через всю полосу до конца третьей.',
    ]);
    expect(out[1].seamed).toBe(true);
    expect(out[2].seamed).toBe(true);
    // Швы стоят рядом, а не вложены друг в друга: иначе полоса чтения считала
    // бы читателя на предыдущей странице.
    const host = document.createElement('div');
    host.innerHTML = out[0].html;
    expect(host.querySelectorAll('.page-seam')).toHaveLength(2);
    expect(host.querySelectorAll('.page-seam .page-seam')).toHaveLength(0);
  });

  it('не склеивает через пустую полосу: между текстом лежит непечатный лист', () => {
    const out = stitchPages(
      [
        { pageNumber: 20, html: '<p>мысль обрывается на</p>' },
        { pageNumber: 21, html: '' },
        { pageNumber: 22, html: '<p>полуслове через вклейку.</p>' },
      ],
      seam,
    );

    expect(paragraphs(out[0].html)).toEqual(['мысль обрывается на']);
    expect(paragraphs(out[2].html)).toEqual(['полуслове через вклейку.']);
  });
});

