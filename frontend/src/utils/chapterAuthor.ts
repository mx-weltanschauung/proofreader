// «К. Маркс. », «Ф. Энгельс. », «К. Маркс и Ф. Энгельс. », «Г. В. Плеханов. »
// — один или несколько инициалов с точками, фамилия, и всё это может
// повториться через «и». Инициалов именно «один или несколько»: у Плеханова
// их два, и на одном инициале его собрание оставалось бы неподписанным.
const INITIALS_NAME = /[А-ЯЁ]\.\s*(?:[А-ЯЁ]\.\s*)*[А-ЯЁ][а-яё]+/.source;

/** Автор в начале заголовка работы. Общий на два потребителя: подпись корешка
 *  (`volumeLabel.ts`) и надстрочник строки содержания (`VolumeOutlineRow`).
 *  Два экземпляра одного правила разошлись бы при первой же правке. */
export const AUTHOR_PREFIX = new RegExp(`^${INITIALS_NAME}(?:\\s+и\\s+${INITIALS_NAME})*\\.\\s+`);

/**
 * Делит заголовок главы на автора и собственно название. Автор — null там,
 * где префикса нет: в томах Плеханова и Выготского заголовки идут без него,
 * и надстрочника у карточки тогда просто не будет.
 */
export function splitAuthor(title: string): { author: string | null; title: string } {
  const match = AUTHOR_PREFIX.exec(title);
  if (!match) return { author: null, title };
  // Хвостовая точка — разделитель, а не часть имени: точки после инициалов
  // остаются на месте.
  const author = match[0].trim().replace(/\.$/, '');
  return { author, title: title.slice(match[0].length) };
}
