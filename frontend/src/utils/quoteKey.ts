import { normalizeQuote } from './quoteMatch';

/** Встречается ли строка в тексте больше одного раза (считаем максимум до двух). */
function occursOnce(text: string, needle: string): boolean {
  const first = text.indexOf(needle);
  if (first < 0) return false;
  return text.indexOf(needle, first + 1) < 0;
}

/**
 * Ключ адреса цитаты: кратчайший префикс головы выделения, встречающийся на
 * полосе ровно один раз.
 *
 * Уникальность берётся ДЛИНОЙ, а не номером вхождения (решение 15): номер —
 * позиционный ключ в маске содержательного, и вставка абзаца выше молча
 * уводит его на чужое место.
 *
 * Префикс растёт по словам: обрывок слова в адресе читается как опечатка, а
 * уникальности на пол-слова раньше целого всё равно не бывает.
 *
 * Уникального префикса не нашлось (повтор строки в стихах) — отдаём голову
 * целиком; на приёме подсветится первое вхождение и будет сказано, что их
 * несколько. Потолка длины нет по решению 13.
 */
export function quoteKey(head: string, pageText: string): string {
  const s = normalizeQuote(head);
  const t = normalizeQuote(pageText);
  if (s === '') return '';

  for (const m of s.matchAll(/\S+/g)) {
    const end = (m.index ?? 0) + m[0].length;
    const candidate = s.slice(0, end);
    if (occursOnce(t, candidate)) return candidate;
  }
  return s;
}

/**
 * Якорь КОНЦА цитаты (`&to=`): кратчайший суффикс хвоста выделения,
 * встречающийся на его полосе ровно один раз.
 *
 * Зеркало quoteKey и живёт рядом с ним не для симметрии: пара якорей — это и
 * есть адрес места после того, как подсветка перестала быть подсветкой одного
 * ключа. Ключ метит, где цитата начинается, этот — где кончается; между ними
 * на приёме и красится всё, что читатель выделил.
 *
 * Отличие от quoteKey ровно одно — сторона роста. Суффикс растёт ВЛЕВО, по
 * словам, по той же причине, по какой префикс растёт вправо: обрывок слова в
 * адресе читается как опечатка, а уникальности на пол-слова раньше целого не
 * бывает.
 *
 * Уникальность считается по полосе, где цитата КОНЧАЕТСЯ, а не начинается:
 * через стык полос это разные полосы (`lastPageText` в quoteSelection.ts).
 * Приём ищет этот якорь вперёд от найденного начала, поэтому уникальность
 * здесь — запас прочности, а не условие правильности: она удерживает якорь от
 * совпадения с ближайшим повтором тех же слов ПОСЛЕ начала цитаты.
 */
export function quoteTail(tail: string, pageText: string): string {
  const s = normalizeQuote(tail);
  const t = normalizeQuote(pageText);
  if (s === '') return '';

  // Начала слов справа налево: последнее слово, два последних, и так далее.
  const starts = [...s.matchAll(/\S+/g)].map((m) => m.index ?? 0).reverse();
  for (const start of starts) {
    const candidate = s.slice(start);
    if (occursOnce(t, candidate)) return candidate;
  }
  return s;
}
