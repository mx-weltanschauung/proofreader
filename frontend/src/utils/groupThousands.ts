/**
 * Разделяет тысячи неразрывным пробелом: 27719 читается как число, только если
 * разделено, а обычный пробел позволил бы браузеру перенести строку посреди
 * числа.
 *
 * Разделитель у `toLocaleString('ru-RU')` не обещан: разные версии ICU дают то
 * U+00A0, то узкий U+202F. Поэтому заменяется любой пробел, а подставляется
 * U+00A0 escape-ом — обычный и неразрывный пробел в исходнике не различить
 * глазом, и правка «поправил пробел» прошла бы незамеченной.
 */
export function groupThousands(n: number): string {
  return n.toLocaleString('ru-RU').replace(/\s/g, '\u00a0');
}
