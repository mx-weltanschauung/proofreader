import type { QuoteMatch } from '../utils/quoteMatch';
import { russianDate } from '../utils/russianDate';
import './QuoteNotice.css';

export interface QuoteNoticeProps {
  match: QuoteMatch | null;
  /** Дата последней правки текста полосы — только если она известна. */
  editedAt?: string;
}

/**
 * Полоска-пометка о судьбе `?quote=` на открытой полосе.
 *
 * Три исхода не путать друг с другом: попадание молчит совсем (читателя
 * привели ровно туда, куда обещала ссылка, — сказать нечего); промах — самый
 * важный случай, ради которого весь механизм и заведён: без вслух сказанного
 * предупреждения читатель решил бы, что цитата просто не годится, а не что
 * место могло измениться; несколько вхождений — отдельная от промаха ветка,
 * потому что цитата НАШЛАСЬ, просто неоднозначно, и это справочная пометка,
 * а не предупреждение — отсюда и разные роли ARIA (`alert` у промаха,
 * `status` у многозначности).
 *
 * Промах без даты правки не утверждает причину: `?quote=` (задача 14) ищет в
 * ОТРИСОВАННОМ тексте, а `head_quote` — сырой срез markdown, и вырезка,
 * начавшаяся внутри разметки, промахнётся честно, даже если полосу никто не
 * правил ни разу. Фраза «текст изменился» в этом случае была бы ложью,
 * которую сам экран тут же опровергает пустой строкой «Правлено:» — дата
 * правки печатается ТОЛЬКО если она есть, поэтому причину называем лишь
 * тогда, когда она подтверждена этой же датой.
 */
export const QuoteNotice: React.FC<QuoteNoticeProps> = ({ match, editedAt }) => {
  if (match === null || match === 'hit') return null;

  if (match === 'miss') {
    const text = editedAt
      ? 'Цитата не нашлась: текст этой полосы изменился с тех пор, как на неё сослались.' +
        ` Последняя правка — ${russianDate(editedAt)}`
      : 'Цитата не нашлась на этой полосе — возможно, текст с тех пор поправили.';
    return (
      <div className="quote-notice quote-notice-miss" role="alert">
        {text}
      </div>
    );
  }

  if (match === 'partial') {
    // Место найдено, а пролёт короче цитаты: якорь конца (`&to=`) в тексте не
    // нашёлся. Роль справочная, а не alert: читателя привели туда, куда
    // обещала ссылка, — сказать надо лишь, почему подсвечено меньше, чем
    // цитировали. Дату называем, если знаем, — у укороченного пролёта причина
    // та же, что у промаха, и других у него не бывает: якорь конца режется из
    // того же отрисованного текста, что и ключ начала, поэтому «промахнулся
    // без правки» (случай head_quote вырезки указателя) здесь невозможен.
    const text = editedAt
      ? 'Конец цитаты не нашёлся — текст полосы правили, подсвечено начало.' +
        ` Последняя правка — ${russianDate(editedAt)}`
      : 'Конец цитаты не нашёлся — подсвечено начало.';
    return (
      <div className="quote-notice quote-notice-partial" role="status">
        {text}
      </div>
    );
  }

  return (
    <div className="quote-notice quote-notice-multiple" role="status">
      Цитата встречается на полосе несколько раз — подсвечено первое.
    </div>
  );
};
