import { createContext, useContext } from 'react';
import type { HintId } from '../hints/registry';

/** Один смонтированный экземпляр выноски: что объясняет и кто именно. */
export interface HintInstance {
  id: HintId;
  /**
   * Отличает экземпляры с одним id. Орган может быть смонтирован не один
   * раз: кнопка «Aa» живёт и в шапке сайта, и в панели потокового чтения, а
   * на экране чтения шапка скрыта через display:none — видна ровно одна
   * копия. Право показаться выдаётся экземпляру, а не идентификатору,
   * иначе обе копии красят себя по одному признаку и та, чей якорь невидим,
   * рисует пузырёк с нулевым прямоугольником в углу экрана.
   */
  token: string;
}

export interface HintsValue {
  /** Экземпляр выноски, которому сейчас дано право показаться. */
  active: HintInstance | null;
  /**
   * Метка текущего «экрана» (pathname). Тем же понятием провайдер уже
   * пользуется сам, чтобы решить, когда сбросить право экрана (spent/locked,
   * см. HintsProvider) — здесь оно отдано наружу, чтобы FeatureHint мог
   * сверяться с ним же, а не заводить второе, своё собственное слежение за
   * pathname: «что такое новый экран» должно быть определено ровно в одном
   * месте.
   */
  screen: string;
  register: (id: HintId, token: string) => void;
  unregister: (id: HintId, token: string) => void;
  /** Виден ли якорь этого экземпляра прямо сейчас. */
  setVisible: (id: HintId, token: string, visible: boolean) => void;
  /**
   * Пузырёк этого экземпляра действительно показался.
   *
   * До этого мгновения замок можно перехватить: якорь шапки сайта («Aa») виден
   * сразу, а собственные органы экрана — оглавление, обрез, скачивание —
   * приезжают после загрузки данных, то есть на несколько сотен миллисекунд
   * позже. Без права перехвата очерёдность решала бы гонка загрузки, а не
   * приоритет, и каждый экран объяснял бы одно и то же «Aa».
   */
  markOpened: (id: HintId, token: string) => void;
  /** Усвоено навсегда: читатель нажал орган или закрыл выноску крестиком. */
  learn: (id: HintId) => void;
  /** Выноска убрана. counted — провисела ли она достаточно, чтобы засчитать показ. */
  close: (id: HintId, counted: boolean) => void;
  /** Забыть, что координатор уже выбирал и замыкал на этом экране. */
  reset: () => void;
}

export const HintsContext = createContext<HintsValue | undefined>(undefined);

/**
 * Возвращает null вне провайдера, а не бросает: органы покрыты собственными
 * тестами, которые рендерят их в одиночку. Выноска — украшение, её отсутствие
 * в изолированном тесте не ошибка.
 */
export function useHints(): HintsValue | null {
  return useContext(HintsContext) ?? null;
}
