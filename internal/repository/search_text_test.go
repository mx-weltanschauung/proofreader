func TestTermsFromTSQuery(t *testing.T) {
	cases := []struct {
		in   string
		want []string
	}{
		{"'гегел'", []string{"гегел"}},
		// Исключённое слово в подсветку не идёт; дубли схлопываются.
		{"'парт' & !'меньшевик' & 'что' <-> 'дела' | 'плехан' | 'парт'", []string{"парт", "что", "дела", "плехан"}},
		// Апостроф внутри леммы Postgres удваивает.
		{"'d''artagnan'", []string{"d'artagnan"}},
		{"", nil},
		{"!'слов'", nil},
		// Ниже — реальный вывод websearch_to_tsquery('ru', …)::text против
		// живой БД (fix round 1): негативная ФРАЗА Postgres заключает в
		// круглые скобки, а не в кавычки сразу после «!», и старый разбор
		// (проверка «!» непосредственно перед кавычкой) эту скобочную форму
		// не ловил — леммы внутри неё утекали в найденные термины.
		//
		// websearch_to_tsquery('ru', 'меньшевики -"второй интернационал"')
		{"'меньшевик' & !( 'втор' <-> 'интернациона' )", []string{"меньшевик"}},
		// websearch_to_tsquery('ru', '"партия рабочих" -"второй интернационал"')
		{"'парт' <-> 'рабоч' & !( 'втор' <-> 'интернациона' )", []string{"парт", "рабоч"}},
		// websearch_to_tsquery('ru', 'партия OR -меньшевик') — OR простого
		// слова и отрицания одиночного слова.
		{"'парт' | !'меньшевик'", []string{"парт"}},
		// websearch_to_tsquery('ru', 'гегель OR "диалектика духа"
		// -"абсолютная идея" -плеханов') — смесь: OR, фраза, негативная
		// фраза, негативное одиночное слово в одном запросе.
		{"'гегел' | 'диалектик' <-> 'дух' & !( 'абсолютн' <-> 'иде' ) & !'плехан'", []string{"гегел", "диалектик", "дух"}},
	}
	for _, c := range cases {
		if got := termsFromTSQuery(c.in); !reflect.DeepEqual(got, c.want) {
			t.Errorf("termsFromTSQuery(%q) = %#v, want %#v", c.in, got, c.want)
		}
	}
}

