func TestCleanSnippet(t *testing.T) {
	in := "# Глава\n**\x01Гегеля\x02** читали[^12] все<sup>3</sup>\x03_курсив_ и   пробелы"
	want := "Глава \x01Гегеля\x02 читали все3 … курсив и пробелы"
	if got := cleanSnippet(in); got != want {
		t.Errorf("cleanSnippet = %q, want %q", got, want)
	}
}

// Угловые скобки в этом корпусе — не только разметка: ими помечают
// восстановленный редактором текст. Такой пометки 129 полос («<ИЗ № 3
// «ОТЕЧЕСТВЕННЫХ ЗАПИСОК»>», «<не>», «<56>»), и общая регулярка «<[^>]+>»
// сносила кусок целиком — вместе со словами И вместе с метками совпадения
// \x01/\x02, то есть отрывок терял ровно то слово, ради которого построен.
// Текст ниже — с полосы 600 работы 142 (Чернышевский, «Библиография»).
func TestCleanSnippetKeepsEditorialAngleBrackets(t *testing.T) {
	cases := []struct{ in, want string }{
		{
			"## БИБЛИОГРАФИЯ\n\n<ИЗ № 3 «\x01ОТЕЧЕСТВЕННЫХ\x02 ЗАПИСОК»>\n\nОсада и взятие Византии",
			"БИБЛИОГРАФИЯ <ИЗ № 3 «\x01ОТЕЧЕСТВЕННЫХ\x02 ЗАПИСОК»> Осада и взятие Византии",
		},
		// Восстановленное слово и восстановленная колонцифра.
		{"он <не> знал", "он <не> знал"},
		{"стр. <56> тома", "стр. <56> тома"},
		// А настоящая разметка по-прежнему снимается: она в отрывке мусор.
		{"все<sup>3</sup> и <b>жирное</b>", "все3 и жирное"},
		{"<table><tbody><tr><td colspan=2>ячейка</td></tr></tbody></table>", "ячейка"},
	}
	for _, c := range cases {
		if got := cleanSnippet(c.in); got != c.want {
			t.Errorf("cleanSnippet(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}
