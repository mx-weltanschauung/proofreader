package models

import "testing"

// Что считается аппаратом, а что настоящей работой, решает один классификатор.
// Раньше этот же смысл держал предикат внутри SQL-шаблона сводок и тест
// TestListWorkSummariesApparatusPredicate, которому ради проверки заголовка
// нужна была живая база. Таблица переехала сюда целиком: границы тут тонкие —
// «Указатель имен» аппарат, а «Указания читателю» нет, хотя у них общие пять
// букв, — и стеречь их дешевле без базы.
func TestIsApparatusTitle(t *testing.T) {
	cases := []struct {
		title     string
		apparatus bool
	}{
		{"Примечания", true},
		{"ПРИМЕЧАНИЯ", true},
		{"Примечание к тексту", true},
		{"Указатель имен", true},
		{"Указатель литературных работ", true},
		{"Тематический указатель", true},
		{"Список неразысканных работ", true},
		{"Даты жизни и деятельности", true},
		{"Содержание", true},
		// «Приложения» и «Подготовительные материалы» — НЕ аппарат даже
		// наверху: так издание называет куски самого автора. Встречный запрос
		// по корпусу 15.09.2026 дал 56 таких корней (1622 полосы) и во всех —
		// текст автора: прошения Ульянова, планы и конспекты Ленина, устав
		// Союза коммунистов, письма Женни Маркс, некролог Плеханова. Ни одной
		// части издательского аппарата. Подробности — миграция 000022.
		{"Приложения", false},
		{"Приложение I", false},
		{"ПРИЛОЖЕНИЯ", false},
		{"Подготовительные материалы", false},
		{"ПОДГОТОВИТЕЛЬНЫЕ МАТЕРИАЛЫ", false},
		// Пробелы по краям приезжают из содержания вместе с заголовком.
		{"  Примечания  ", true},
		// Ниже — настоящие работы, начинающиеся похоже. Предикат привязан к
		// началу строки и к целому префиксу, а не к вхождению.
		{"ЧТО ДЕЛАТЬ?", false},
		{"Указания читателю", false},
		{"Спискам не верить", false},
		{"О содержании понятия", false},
		{"Письмо о примечаниях", false},
		{"Приложимость диалектики", false},
		{"", false},
	}

	for _, c := range cases {
		if got := IsApparatusTitle(c.title, true); got != c.apparatus {
			t.Errorf("IsApparatusTitle(%q, topLevel=true) = %v, ожидалось %v",
				c.title, got, c.apparatus)
		}
		// Подглавой — не аппарат никогда, какой бы ни был заголовок: признак
		// подглаве достаётся только наследованием от родителя, в
		// ChapterRepository.Create. Почему так — TestNestedTitlesAreNotApparatus.
		if got := IsApparatusTitle(c.title, false); got {
			t.Errorf("IsApparatusTitle(%q, topLevel=false) = true, ожидалось false",
				c.title)
		}
	}
}

// Оба списка классификатора работают только у главы верхнего уровня.
//
// Префиксный список раньше проверялся на любой глубине, и это стоило дорого:
// по корпусу набралось 40 глав, помеченных аппаратом внутри настоящих работ,
// плюс 60 их подглав, получивших признак наследованием, — 344 полосы. Все 40
// оказались текстом автора, ни одной настоящей частью аппарата издания.
// Худший случай — «Приложение» (100 полос) внутри «Теорий прибавочной
// стоимости» Маркса, чья подглава «Доход и его источники. Вульгарная
// политическая экономия» (98 полос текста самого Маркса) числилась аппаратом
// по наследству: поиск считал эти полосы «в аппарате», а снятие аппарата тома
// снесло бы их вместе с настоящим аппаратом.
//
// Встречный запрос по корпусу показал и то, что правило безопасно сузить
// целиком, а не по одному слову: вглубь срабатывали только «содержание» (18
// раз), «приложени» (17), «примечани» (4) и «список» (1) — ровно те четыре
// слова, которыми называет свои куски и сам автор. «Указател», «даты жизни»,
// «тематический указател» и «подготовительные материалы» не срабатывали
// вглубь ни разу, так что разделение списка на «глубокий» и «верхний» не
// купило бы сегодня ничего.
//
// Заголовки ниже — живые, из corpus; рядом работа, внутри которой глава сидит.
func TestNestedTitlesAreNotApparatus(t *testing.T) {
	nested := []struct {
		title string
		where string
	}{
		{"Приложение", "Теории прибавочной стоимости, ч. III — работа 153"},
		{"Приложения", "Теории прибавочной стоимости, ч. I — работа 151"},
		{"Приложение II. Ответ критикам", "К вопросу о развитии монистического взгляда — Плеханов, работа 42"},
		{"Приложение. Попытка объединения «Искры» с «Рабочим Делом»", "ЧТО ДЕЛАТЬ? — Ленин, работа 49"},
		{"Приложение к письму", "102. Г. Е. ЗИНОВЬЕВУ — Ленин, работа 126"},
		{"Содержание", "ТЕТРАДЬ «α» («АЛЬФА») — Тетради по империализму, работа 155"},
		{"Список цитат из книги Шульце-Геверница «Британский империализм»", "ТЕТРАДЬ «λ» — работа 155"},
		{"Примечание к тезису «О списке кандидатов в Учредительное собрание»", "О списке кандидатов — Ленин, работа 98"},
		{"Примечание к изд. «Шиповника»", "Часть вторая. Политические взгляды Чернышевского — Плеханов, работа 149"},
		// Настоящий аппарат подглавой признак тоже не получает от заголовка —
		// он получает его наследованием, и на этом держится сужение правила.
		{"Именной указатель", "подглава — признак придёт от родителя-аппарата"},
		{"Примечания", "подглава — признак придёт от родителя-аппарата"},
	}

	for _, c := range nested {
		if IsApparatusTitle(c.title, false) {
			t.Errorf("IsApparatusTitle(%q, topLevel=false) = true, ожидалось false (%s)",
				c.title, c.where)
		}
	}
}

// Второй список классификатора — совпадение заголовка ЦЕЛИКОМ и только у
// главы верхнего уровня.
//
// Он заведён потому, что префиксное правило выше промахивается мимо обратного
// порядка слов («Именной указатель» не начинается с «указател») и не знает
// «Комментариев», «Литературы» и «Послесловия» вовсе — из-за чего у издания
// Выготского на 169 глав не было размечено аппаратом НИ ОДНОЙ, а это ровно тот
// корпус, ради которого рычаг снятия и заведён.
//
// Обе половины правила куплены встречным запросом по живому корпусу, и обе
// проверяются ниже: «содержит» утащило бы в аппарат «ПОСЛЕСЛОВИЕ К ТЕЗИСАМ…»
// Ленина, а разрешённый в подглавах список — его же «Послесловие» внутри
// «УДЕРЖАТ ЛИ БОЛЬШЕВИКИ ГОСУДАРСТВЕННУЮ ВЛАСТЬ?», то есть текст автора.
func TestIsApparatusTopTitleList(t *testing.T) {
	cases := []struct {
		title     string
		topLevel  bool
		apparatus bool
	}{
		// Живые заголовки аппарата, мимо которых промахивается префикс.
		{"Именной указатель", true, true},
		{"Предметный указатель", true, true},
		{"Комментарии", true, true},
		{"КОММЕНТАРИИ", true, true},
		{"Литература", true, true},
		{"Послесловие", true, true},
		{"Вступительная статья", true, true},
		{"От редакционной коллегии", true, true},
		{"  Комментарии  ", true, true},
		// Те же слова подглавой — текст автора, а не аппарат. Все три пары
		// взяты запросом по chapters: «Послесловие» внутри работы Ленина,
		// «Литература» внутри «КАРЛА МАРКСА».
		{"Послесловие", false, false},
		{"Литература", false, false},
		{"Комментарии", false, false},
		{"Именной указатель", false, false},
		// Настоящие работы корпуса с теми же словами — не аппарат нигде.
		{"К. Маркс. Комментарии к парламентским дебатам", true, false},
		{"ПОСЛЕСЛОВИЕ К ТЕЗИСАМ ПО ВОПРОСУ О НЕМЕДЛЕННОМ ЗАКЛЮЧЕНИИ СЕПАРАТНОГО И АННЕКСИОНИСТСКОГО МИРА", true, false},
		{"Послесловие ко второму изданию", true, false},
		{"Послесловие к французскому изданию", true, false},
		{"ПАРТИЙНАЯ ОРГАНИЗАЦИЯ И ПАРТИЙНАЯ ЛИТЕРАТУРА", true, false},
		{"Искусство и литература", true, false},
		{"Вступительная статья к русскому переводу книги К. Бюлера «Очерк духовного развития ребенка»", true, false},
		{"ОТ РЕДАКЦИИ ЦЕНТРАЛЬНОГО ОРГАНА РСДРП", true, false},
		{"Александр Юнг. «Лекции о современной литературе немцев»", true, false},
	}

	for _, c := range cases {
		if got := IsApparatusTitle(c.title, c.topLevel); got != c.apparatus {
			t.Errorf("IsApparatusTitle(%q, topLevel=%v) = %v, ожидалось %v",
				c.title, c.topLevel, got, c.apparatus)
		}
	}
}
