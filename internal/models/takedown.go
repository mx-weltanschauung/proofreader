package models

// Снятие аппарата тома — необратимая операция под правовую стойку проекта
// (реактивную: ничего не снимаем превентивно, снимаем по первому письму).
// Типы ниже описывают её план; он же — отчёт о выполненном, потому что план
// читается тем же условием, каким идёт снос, и разойтись им нечем.

// ApparatusChapter — корень снимаемого поддерева аппарата с его диапазоном
// полос.
//
// Корень, а не «глава верхнего уровня», и разница куплена дорого. Аппаратом
// бывает помечена глава ВНУТРИ настоящей работы, а снос берёт её (условие
// смотрит на is_apparatus, а не на уровень) — значит план обязан её называть.
// Перечисляй он только parent_id IS NULL — оператор увидел бы один
// «Предметный указатель», подтвердил бы снятие и необратимо снёс бы сто полос
// тела.
//
// До 15.09.2026 такую разметку делал сам классификатор: префиксное правило
// проверялось на любой глубине, и «Приложение» подглавой внутри работы
// помечалось аппаратом — у Маркса сто полос его собственного текста внутри
// «Теорий прибавочной стоимости». По корпусу таких набралось 40 корней и 60
// подглав по наследству; правило сужено до глав верхнего уровня
// (models.IsApparatusTitle), разметка снята миграцией 000021. Корни в плане
// остаются: признак правится руками (PUT /works/{id}/chapters/{id} принимает
// is_apparatus), и ручная пометка вглубь по-прежнему законна.
type ApparatusChapter struct {
	ID        int64  `json:"id"`
	Title     string `json:"title"`
	StartPage int    `json:"start_page"`
	EndPage   int    `json:"end_page"`
	// Subchapters — сколько подглав уйдёт вместе с ней.
	Subchapters int `json:"subchapters"`
	// ParentTitle — заголовок родителя, если глава сидит ВНУТРИ работы, не
	// помеченной аппаратом. Пусто у главы верхнего уровня. Непустое значение —
	// повод присмотреться: скорее всего это авторское приложение, а не
	// аппарат издания.
	ParentTitle string `json:"parent_title,omitempty"`
}

// ApparatusChild — служебная работа тома (передние листы), уходящая целиком.
//
// Входит в снятие аппарата по решению владельца: вступительная статья — самый
// рискованный слой из отделимых, у неё живой автор. Имя команды говорит про
// аппарат, а сносит она больше, поэтому план печатает детей поимённо.
type ApparatusChild struct {
	ID    int64  `json:"id"`
	Title string `json:"title"`
	Role  string `json:"role"`
	Pages int    `json:"pages"`
}

// ApparatusPlan — что снятие аппарата тома уберёт.
type ApparatusPlan struct {
	WorkID    int64  `json:"work_id"`
	WorkTitle string `json:"work_title"`
	// Chapters — главы-аппарат верхнего уровня. Подглавы сюда не попадают,
	// но снимаются вместе с родителем и посчитаны в ChapterCount.
	Chapters     []ApparatusChapter `json:"chapters"`
	ChapterCount int                `json:"chapter_count"`
	// PageCount — полосы, попадающие в диапазоны глав-аппарата. Вместе с
	// полосой уходят её версии, вырезки указателя и предложения читателей —
	// это каскады схемы.
	PageCount int `json:"page_count"`
	// ConceptCount — статьи предметного указателя, пришедшие ИЗ ЭТОГО ТОМА
	// (index_concept_articles.work_id = этот том), а не понятия каталога
	// целиком: с миграции 000026 (задача 11) у понятия бывает и статья
	// другого издания, чей источник — не этот том, и её снятие вместе с
	// понятием было бы чужой потерей (см. apparatus_repository.go, Remove).
	// Указатель входит в снятие потому, что это тот же печатный объект,
	// перенесённый в базу: оставить его — снять обложку, оставив содержимое.
	ConceptCount int `json:"concept_count"`
	// Children — служебные работы тома.
	Children []ApparatusChild `json:"children"`
	// PagesOutsideChapters — полосы тома, не накрытые НИ ОДНОЙ главой.
	//
	// Снятие аппарата идёт по диапазонам глав, и эти полосы оно не тронет —
	// какими бы они ни были по содержанию. Считаются и хвост тома, и
	// промежутки между соседними главами. Замер на ленинском томе 45: таких
	// полос 31, из них двенадцать последних (719—730) — «Содержание» и
	// колофон, то есть аппарат чистой воды, остающийся лежать.
	//
	// В плане стоит не ради полноты, а чтобы щель была видна оператору:
	// решение «снять том целиком или разметить главу» принимает он, и принять
	// его можно только зная, что что-то остаётся.
	PagesOutsideChapters int `json:"pages_outside_chapters"`
	// StoragePaths — превью снимаемых полос. Каскад Postgres про хранилище не
	// знает; объекты сносит обработчик. Наружу не отдаётся: читателю плана
	// нужен счёт, а не список ключей.
	StoragePaths []string `json:"-"`
	// AudioPaths — записи человека в главах аппарата (ключи аудиобакета).
	// Строки уходят каскадом вместе с главами; объекты сносит обработчик.
	AudioPaths []string `json:"-"`
	// TrackPaths — синтезированные дорожки тома, задевающие хоть одну
	// снимаемую полосу (ключи аудиобакета). Раскладка синтеза аппарат не
	// озвучивает, так что в штатном томе список пуст; он страхует от
	// дорожки прежней раскладки или главы, размеченной аппаратом уже после
	// синтеза. Строки сносит Remove, объекты — обработчик, поштучно: прочий
	// синтез тома лежит под тем же префиксом и остаётся жить.
	TrackPaths []string `json:"-"`
	// TrackCount — число таких дорожек, для счёта в плане.
	TrackCount int `json:"track_count"`
}

// Empty отвечает, нечего ли снимать.
//
// Нужен, чтобы отказать вслух. Разметка аппарата в корпусе неполна — она
// ставится классификатором по заголовку и правится руками, — и «снято ноль»
// на неразмеченном томе выглядит как успешное снятие, им не являясь. Именно
// так рычаг и сломался бы на издании Выготского, ради которого он заведён.
func (p ApparatusPlan) Empty() bool {
	return p.ChapterCount == 0 && len(p.Children) == 0
}
