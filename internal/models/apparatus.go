package models

import "strings"

// apparatusPrefixes — начала заголовков, по которым глава опознаётся как
// аппарат: примечания, указатели, списки, даты жизни, содержание. Границы тут
// тонкие и держатся началом строки, а не вхождением: «Указатель имен» —
// аппарат, «Указания читателю» — работа, хотя у них общие пять букв.
//
// «приложени» и «подготовительные материалы» отсюда УБРАНЫ 16.09.2026, и это
// не оплошность списка, а вывод из замера — см. миграцию 000022, которая
// снимает поставленный ими признак. Коротко: так издание называет куски
// САМОГО АВТОРА. Встречный запрос по корпусу дал 56 таких корней верхнего
// уровня (1622 полосы) и во всех до единого — текст автора: прошения
// Ульянова, планы и конспекты Ленина к собственным статьям, его анкеты и
// удостоверения, устав Союза коммунистов, письма Женни Маркс, некролог
// Плеханова. Ни одной части издательского аппарата.
//
// Это тот же довод, которым 000021 сняла признак ВГЛУБЬ, просто применённый
// наверху: цена ошибки там и тут одна — takedown.sh --apparatus снёс бы эти
// полосы вместе с настоящим аппаратом, а поиск числит их «в аппарате» и
// занижает счёт «в тексте».
var apparatusPrefixes = []string{
	"примечани", "указател", "список", "даты жизни",
	"содержание", "тематический указател",
}

// apparatusTopTitles — заголовки, опознаваемые ЦЕЛИКОМ.
//
// Список заведён после замера: префиксное правило выше промахивается мимо
// обратного порядка слов («Именной указатель» не начинается с «указател») и не
// знает «Комментариев», «Литературы» и «Послесловия» вовсе. Цена промаха
// оказалась не теоретической — у издания Выготского не было размечено
// аппаратом ни одной главы из 169, а это ровно тот корпус, ради которого рычаг
// снятия аппарата и заведён.
//
// Целиком, а не вхождением: «содержит» утаскивает в аппарат десятки настоящих
// работ — «ПОСЛЕСЛОВИЕ К ТЕЗИСАМ…» Ленина, «Комментарии к парламентским
// дебатам» Маркса, «Партийная организация и партийная литература».
var apparatusTopTitles = []string{
	"именной указатель", "предметный указатель",
	"комментарии", "литература", "послесловие",
	"вступительная статья", "от редакционной коллегии",
}

// IsApparatusTitle отвечает, аппарат ли это, по заголовку и месту главы в
// дереве. topLevel — у главы нет родителя.
//
// Единственное место, где живёт этот вопрос. Раньше он стоял предикатом внутри
// SQL-шаблона сводок; теперь классификация происходит один раз — при создании
// главы, — а ответ хранится в chapters.is_apparatus. Смысл держат
// TestIsApparatusTitle, TestNestedTitlesAreNotApparatus и
// TestIsApparatusTopTitleList.
//
// По заголовку аппарат опознаётся ТОЛЬКО у главы верхнего уровня. Подглаве
// признак достаётся единственным путём — наследованием от родителя
// (ChapterRepository.Create), и это не перестраховка, а вывод из замера.
//
// Префиксный список раньше проверялся на любой глубине, и корпус заплатил за
// это 40 главами, помеченными аппаратом внутри настоящих работ, плюс 60 их
// подглав по наследству — 344 полосы. Все 40 оказались текстом автора:
// приложения Маркса и Ленина к собственным работам, оглавления и выписки
// ленинских тетрадей, полемические приложения Плеханова. Ни одной настоящей
// части аппарата издания среди них не было. Худший случай — «Приложение» (100
// полос) внутри «Теорий прибавочной стоимости», чья подглава «Доход и его
// источники. Вульгарная политическая экономия» (98 полос текста самого
// Маркса) числилась аппаратом по наследству: поиск считал эти полосы «в
// аппарате», а снятие аппарата тома снесло бы их вместе с настоящим аппаратом.
//
// Сузить правило целиком, а не по одному слову, позволил тот же встречный
// запрос: вглубь срабатывали только «содержание» (18 раз), «приложени» (17),
// «примечани» (4) и «список» (1) — ровно те четыре слова, которыми называет
// свои куски и сам автор. «Указател», «даты жизни», «тематический указател» и
// «подготовительные материалы» не срабатывали вглубь ни разу, так что деление
// списка на «глубокий» и «верхний» не купило бы сегодня ничего.
//
// Списки повторены дословно в миграциях 000015 и 000019, которые проставляли
// тот же признак задним числом, а 000021 снимает его с разметки, сделанной
// прежним, глубоким правилом. Меняя здесь, пиши новую миграцию.
func IsApparatusTitle(title string, topLevel bool) bool {
	if !topLevel {
		return false
	}
	t := strings.ToLower(strings.TrimSpace(title))
	for _, p := range apparatusPrefixes {
		if strings.HasPrefix(t, p) {
			return true
		}
	}
	for _, whole := range apparatusTopTitles {
		if t == whole {
			return true
		}
	}
	return false
}
