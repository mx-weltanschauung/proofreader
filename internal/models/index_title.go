package models

import (
	"strings"
	"unicode"

	"golang.org/x/text/unicode/norm"
)

// indexTitleDashes — виды тире и дефиса, которые сводятся в ключе к
// дефису-минусу (сам он в списке не нужен). Печать указателя путает их между
// собой: «1905-1907 гг.» в заглавии понятия и «1905— 1907 гг.» в цели
// отсылки на него, «Общественно – экономическая» против
// «Общественно-экономическая». В ленинском корпусе встречаются три («—»,
// «–», «-»); остальные перечислены, чтобы новый указатель не разошёлся
// ключом на знаке, которого этот не показал.
const indexTitleDashes = "‐‑‒–—―−"

// NormalizeIndexTitle приводит заголовок понятия или подрубрики к ключу
// сравнения: NFC, обрезка краёв, схлопывание внутренних пробелов, регистр,
// ё→е, вид тире не различается, а пробел остаётся только между двумя
// словесными знаками (буква, цифра, комбинирующий знак). И всё.
//
// Последние два правила — про набор, а не про смысл: цель отсылки и
// заглавие понятия, на которое она указывает, расходятся пробелом у тире
// («1914—1918 гг.» против «1914— 1918 гг.», «Социалисты - революционеры»
// против «Социалисты-революционеры»), видом тире и пробелом у скобки или
// кавычки («(«тесняки» )», «« Крестьянская»», «РСДРП (б)»). Пробел между
// двумя словами значим по-прежнему: «не рабочий» и «нерабочий» — разные
// ключи. Замер 24.09.2026: из 696 неразрешённых отсылок ленинского указателя
// своё понятие начали находить 78, коллизий ключей понятий и подрубрик ноль.
// Побочно правило снимает и пробел после запятой или точки
// («рсдрп,рсдрп(б)») — коллизий это тоже не дало.
//
// Ничего нечёткого сверх этого — ни отбрасывания хвоста после запятой, ни
// содержимого скобок: сведение статей разных указателей решено ТОЧНЫМ
// совпадением ключа, «Абстракция, абстрактное и конкретное» и «Абстрактное
// и конкретное» не сойдутся, и чинит это куратор. Сводит ключ и понятия
// разных изданий (resolveConcept), так что с этим правилом сведение, скажем,
// марксова указателя с ленинским стало на те же знаки грубее. Близнецы этого выражения —
// lenin_index_stitch.normalize_title в Питоне (проверяется той же таблицей
// testdata/index_title_keys.json) и пересчёт хранимых ключей миграцией
// 000033; расходиться им нельзя.
func NormalizeIndexTitle(s string) string {
	s = norm.NFC.String(s)
	s = strings.ToLower(strings.Join(strings.Fields(s), " "))
	s = strings.ReplaceAll(s, "ё", "е")

	runes := []rune(s)
	var b strings.Builder
	b.Grow(len(s))
	for i, r := range runes {
		switch {
		case strings.ContainsRune(indexTitleDashes, r):
			b.WriteByte('-')
		case r == ' ':
			// Края уже срезаны strings.Fields, поэтому соседи есть всегда.
			if isIndexTitleWordRune(runes[i-1]) && isIndexTitleWordRune(runes[i+1]) {
				b.WriteByte(' ')
			}
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// isIndexTitleWordRune — словесный знак: буква, цифра или комбинирующий знак
// (категории L, N и M Юникода; у близнеца в Питоне — unicodedata.category,
// первая буква «L», «N» или «M»). Комбинирующий — чтобы пробел после
// ударения («что́ делать») не терял границу слова.
func isIndexTitleWordRune(r rune) bool {
	return unicode.IsLetter(r) || unicode.IsNumber(r) || unicode.IsMark(r)
}
