package seo

import "container/list"

// Purge выбрасывает всё, что обработчик держит в памяти: и готовые страницы,
// и карточки og:image. Отвечает, сколько записей унесло — сперва страниц,
// потом карточек.
//
// Заведён под снятие тома. У этих двух кэшей нет ни путей инвалидации, ни
// способа адресовать записи снятой сущности: ключ — путь читальни, а после
// удаления строки собрать все её пути уже неоткуда (главы, полосы, карточки).
// Поэтому сброс тотальный, и цена его мала: страницы отдаются краулерам,
// которых в журнале десятки в сутки, а не читателям.
//
// Срок годности тут не спасает и разница между двумя кэшами это показывает:
// страница живёт час, а карточка — сутки (cardCacheTTL), то есть снятый том
// продолжал бы отдавать превью в мессенджеры целые сутки после снятия.
//
// nil-приёмник допустим и означает «краулерской половины нет»: так собран
// сервер в части тестов.
func (h *Handler) Purge() (pages int, cards int) {
	if h == nil {
		return 0, 0
	}
	return h.cache.purge(), h.cards.purge()
}

// purge опустошает кэш и отвечает, сколько записей в нём было.
//
// Заодно двигает поколение. Без этого сброс отменялся бы сам собой: рендер,
// начатый ДО снятия тома, кладёт готовую страницу в кэш после того, как
// вернётся, — то есть уже после сброса, — и снятый том жил бы там свой час
// (а карточка сутки). Окно невелико, но именно в него и приходит всплеск
// краулеров, ради которого кэш заведён.
func (c *docCache) purge() int {
	if c == nil {
		return 0
	}
	c.mu.Lock()
	defer c.mu.Unlock()

	n := c.order.Len()
	c.order.Init()
	c.items = map[string]*list.Element{}
	c.size = 0
	c.gen++
	return n
}

// generation — метка текущего содержимого кэша. Снимается ДО рендера и
// предъявляется при записи.
func (c *docCache) generation() uint64 {
	if c == nil {
		return 0
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.gen
}

// putIfFresh кладёт запись, только если с момента снятия метки кэш не
// сбрасывали. Отвечает, положил ли.
func (c *docCache) putIfFresh(key string, entry *cacheEntry, gen uint64) bool {
	if c == nil {
		return false
	}
	c.mu.Lock()
	stale := c.gen != gen
	c.mu.Unlock()
	if stale {
		return false
	}
	c.put(key, entry)
	return true
}
