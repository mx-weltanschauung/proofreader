-- Откат вложенности подрубрик.
--
-- ЧТО ЭТОТ ОТКАТ ДЕЛАЕТ С ДАННЫМИ: сама по себе колонка parent_id уносит
-- только связь «ребёнок — родитель»; строки подрубрик и их адреса остаются
-- на месте, дети просто становятся плоскими соседями своих родителей.
--
-- ЧЕГО ОН НАМЕРЕННО НЕ ДЕЛАЕТ: он НЕ удаляет вложенные подрубрики ради того,
-- чтобы пролезть в старое ограничение. У index_references.rubric_id стоит
-- ON DELETE CASCADE, и снос вложенных подрубрик унёс бы вместе с ними 2597
-- ленинских адресов — тихая потеря данных ради успеха отката.
--
-- Поэтому на базе, куда уже ввезён вложенный указатель, последняя строка
-- (возврат прежнего ограничения) УПАДЁТ на дубле ключа в статье. Это
-- задумано: весь файл выполняется одним неявным транзакционным блоком, так
-- что упавший откат не меняет НИЧЕГО, и оператор видит отказ вместо молча
-- опустевших статей. Откатывать после ввоза — значит сперва решить, что
-- делать со вложенными строками, и решить это руками.
--
-- Что при этом остаётся прибрать (проверено прогоном, не выведено): схема и
-- данные целы, но golang-migrate помечает версию грязной ДО выполнения файла
-- и после отказа оставляет в schema_migrations «31, dirty=true», хотя схема
-- на деле осталась 32-й. Чинится одной командой:
--     DB_NAME=<база> go run cmd/migrate/main.go force 32
ALTER TABLE index_rubrics DROP CONSTRAINT IF EXISTS index_rubrics_article_parent_title_key;
DROP INDEX IF EXISTS idx_index_rubrics_parent_id;
ALTER TABLE index_rubrics DROP COLUMN IF EXISTS parent_id;
ALTER TABLE index_rubrics
    ADD CONSTRAINT index_rubrics_article_id_title_key_key UNIQUE (article_id, title_key);
