-- Снятие аппарата с глав, сидящих ВНУТРИ настоящих работ.
--
-- Разметку сделало префиксное правило классификатора (models.apparatusPrefixes),
-- которое до этой миграции проверялось на ЛЮБОЙ глубине — ограничение
-- «только верхний уровень» стояло лишь у второго списка, apparatusTopTitles.
-- Отсюда «Приложение» подглавой внутри работы автора считалось аппаратом, а
-- его подглавы получали признак наследованием (и в 000015, и в 000019).
--
-- Замер по корпусу на 15.09.2026: 40 таких корней и 60 их подглав, 344 полосы.
-- Все 40 оказались текстом автора — приложения Маркса и Ленина к собственным
-- работам, оглавления и выписки ленинских тетрадей, полемические приложения
-- Плеханова; ни одной настоящей части аппарата издания. Худший случай —
-- «Приложение» (100 полос) внутри «Теорий прибавочной стоимости», чья
-- подглава «Доход и его источники. Вульгарная политическая экономия» (98 полос
-- текста самого Маркса) числилась аппаратом по наследству: поиск считал эти
-- полосы «в аппарате», а снятие аппарата тома снесло бы их вместе с настоящим
-- аппаратом.
--
-- Почему это первая миграция, которая СНИМАЕТ признак, хотя 000015 и 000019
-- намеренно только ставили. Запрет снимать правилом защищает ручную разметку:
-- снимающая ветка затёрла бы чужую работу. Здесь он не нарушен, и это
-- проверено встречным запросом, а не рассуждением:
--
--   SELECT count(*) FILTER (WHERE m), count(*) FILTER (WHERE NOT m) FROM (
--     SELECT lower(btrim(c.title)) LIKE ANY (ARRAY[...восемь префиксов...]) AS m
--     FROM chapters c JOIN chapters p ON p.id = c.parent_id
--     WHERE c.is_apparatus AND NOT p.is_apparatus) t;
--   -- 40 | 0
--
-- Ноль во втором столбце означает, что ручных пометок вглубь нет ни одной:
-- всё, что снимается ниже, поставлено тем самым правилом, которое отменяется.
--
-- Адресоваться списком id нельзя: id глав локально и на боевом расходятся
-- (тома заливаются на боевой через API, и ключи там свои). Поэтому условие —
-- то же самое, каким признак ставился.

WITH RECURSIVE seeds AS (
    -- Корень: помечен аппаратом, родитель аппаратом НЕ помечен (значит признак
    -- пришёл не по наследству), а заголовок объясняется префиксным правилом.
    SELECT c.id
    FROM chapters c
    JOIN chapters p ON p.id = c.parent_id
    WHERE c.is_apparatus
      AND NOT p.is_apparatus
      AND lower(btrim(c.title)) LIKE ANY (ARRAY[
          'примечани%', 'указател%', 'список%', 'даты жизни%', 'приложени%',
          'содержание%', 'подготовительные материалы%', 'тематический указател%'
      ])
),
tree AS (
    SELECT id FROM seeds
    UNION ALL
    -- Подглавы корня: их признак — наследство от него, снимается вместе с ним.
    SELECT c.id FROM chapters c JOIN tree t ON c.parent_id = t.id
)
UPDATE chapters SET is_apparatus = false
WHERE is_apparatus AND id IN (SELECT id FROM tree);
