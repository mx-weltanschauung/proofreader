-- Шаг вниз ОТКАЗЫВАЕТ, пока в margin_notes есть строки: снос таблицы унёс бы
-- личные заметки читателей, а их нигде больше нет. Отказ — первым
-- оператором; файл выполняется одним неявным блоком, поэтому упавший откат
-- не меняет ничего. golang-migrate помечает целевую версию грязной ДО
-- выполнения файла: после отказа schema_migrations читается «43, dirty=true»,
-- хотя схема на 45, — чинится
-- `DB_NAME=<база> go run cmd/migrate/main.go force 45`.
-- Снять заметки осознанно: удалить строки, затем повторить шаг вниз.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM margin_notes) THEN
        RAISE EXCEPTION 'в базе есть заметки читателей: шаг вниз 000045 снёс бы их — сначала удалите заметки';
    END IF;
END $$;

DROP TABLE IF EXISTS margin_notes;
