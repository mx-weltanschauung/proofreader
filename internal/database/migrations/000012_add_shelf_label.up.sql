-- Подпись корешка, заданная руками. Заголовки томов в собрании одинаковы
-- («…Полное собрание сочинений. Том 1»), а вывести подпись из глав удаётся
-- не всегда: у 45 томов Ленина одной работой честно называются восемь.
-- Остальным нужен способ сказать имя тома прямо.
--
-- Пустая строка, а не NULL: '' и NULL означали бы одно состояние — «подписи
-- нет», — а два способа записать одно это ветвление в каждой проверке. Тот же
-- выбор уже сделан для role и numbering_style.
ALTER TABLE works
    ADD COLUMN shelf_label TEXT NOT NULL DEFAULT '';

COMMENT ON COLUMN works.shelf_label IS
    'Подпись корешка, заданная руками; пусто — подпись выводится из глав';
