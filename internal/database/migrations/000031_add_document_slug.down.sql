-- Откат снимает адреса разборов НАВСЕГДА: повторный накат слепит слаг заново
-- из номера строки ('razbor-' || id), а не из заглавия, и внешние ссылки вида
-- /documents/{ник}/{слаг}, уже разошедшиеся по мессенджерам и осевшие в
-- поисковой выдаче, после цикла вниз-вверх укажут в никуда. Это цена отката,
-- названная вслух, а не забытая: данные разбора целы, адрес — нет.
--
-- Отказа, как у 000028, здесь нет намеренно: там откат ПУБЛИКОВАЛ бы
-- непроверенный текст (порча видимого), здесь он ломает адресацию, которой
-- без нового кода всё равно никто не пользуется — старый код адресует
-- разбор номером.
ALTER TABLE documents DROP CONSTRAINT IF EXISTS documents_author_slug_key;
ALTER TABLE documents DROP COLUMN IF EXISTS slug;
