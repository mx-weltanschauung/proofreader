-- Откат освобождает все отставленные ники разом: имена ушедших читателей
-- снова можно занять, и подписи под их разборами и подборками снова смогут
-- указать на живого человека, который этого не писал.
--
-- Это названо вслух, а не забыто: переносить отставку в старую схему некуда
-- (таблица и есть единственное место, где она живёт), а откат — операция
-- разработчика на своей копии, где ушедших читателей нет. На боевом откат
-- этой миграции означает возврат ровно того дефекта, ради которого она
-- заведена.
DROP TABLE IF EXISTS retired_nicknames;
