-- Свободный текст о томе, заданный руками: почему в скане не хватает полос,
-- откуда взят источник, что с ним ещё не так. Карточка тома отвечает на
-- «откуда мало страниц» подписью корешка не всегда — shelf_label называет
-- том, а не объясняет его состояние, и для объяснения нужно отдельное поле.
--
-- Пустая строка, а не NULL: '' и NULL означали бы одно состояние — «описания
-- нет», — а два способа записать одно это ветвление в каждой проверке. Тот же
-- выбор уже сделан для shelf_label, role и numbering_style.
ALTER TABLE works
    ADD COLUMN description TEXT NOT NULL DEFAULT '';

COMMENT ON COLUMN works.description IS
    'Описание тома, заданное руками; пусто — описания нет';
