-- Снятие аппарата с «Приложений» и «Подготовительных материалов» ВЕРХНЕГО уровня.
--
-- Парная к 000021. Та сняла признак с глав, сидящих внутри настоящих работ, и
-- оставила верхний уровень как есть, потому что правило (models.apparatusPrefixes)
-- там по-прежнему срабатывало. Замер 15.09.2026 показал, что довод 000021
-- ничем не ограничен глубиной: наверху этими словами издание называет куски
-- САМОГО АВТОРА ровно так же, как и внутри работ.
--
-- Встречный запрос по корпусу — 56 корней верхнего уровня, 802 главы вместе с
-- подглавами, 1622 полосы. Просмотрены ВСЕ 56, и во всех до единого текст
-- автора:
--
--   ПОДГОТОВИТЕЛЬНЫЕ МАТЕРИАЛЫ (Ленин, 9 томов) — «НАБРОСОК РЕЗОЛЮЦИИ ПО
--       НАЦИОНАЛЬНОМУ ВОПРОСУ», «ТЕЗИСЫ РЕФЕРАТА», «ПЛАН СТАТЬИ „КАРЛ МАРКС"»:
--       планы и конспекты Ленина к собственным работам.
--   ПРИЛОЖЕНИЯ (Ленин) — «ПРОШЕНИЯ В. И. УЛЬЯНОВА (ЛЕНИНА) 1887—18…»,
--       «ДИРЕКТОРУ БРИТАНСКОГО МУЗЕЯ», «ТЕЛЕГРАММА В. В. ВОРОВСКОМУ»,
--       «АНКЕТА ДЛЯ ДЕЛЕГАТОВ X ВСЕРОССИЙСКОЙ…»: его письма и документы.
--   Приложения (Маркс и Энгельс) — «Устав Союза коммунистов», «Прошение
--       Ф. Энгельса о разрешении пребывания», «Женни Маркс — Фридриху Энгельсу».
--   Приложение. Л. Мечников (некролог) — текст самого Плеханова.
--
-- Худший случай назван поимённо: том 50 Ленина, «ПРИЛОЖЕНИЯ» (полосы 361—392)
-- с 46 подглавами по наследству — его письма и телеграммы. takedown.sh
-- --apparatus снёс бы эти 32 полосы вместе с настоящим аппаратом, а поиск
-- числил их «в аппарате» и занижал счёт «в тексте».
--
-- Спорная строка ровно одна, и она называется вслух: у Плеханова (том 6)
-- внутри «Приложений» сидит «Вступительное замечание редактора». Оно уедет в
-- текст вместе с разделом. Цена признана меньшей, чем обратная — сотни полос
-- автора под ножом снятия аппарата.
--
-- Адресоваться списком id нельзя: id глав локально и на боевом расходятся
-- (тома заливаются через API, ключи там свои). Поэтому условие — то же самое,
-- каким признак ставился, и снимается ровно то, что оно же и поставило.

WITH RECURSIVE seeds AS (
    -- Корень: верхнего уровня (признак пришёл от заголовка, а не по
    -- наследству) и заголовок объясняется снимаемой парой префиксов.
    SELECT c.id
    FROM chapters c
    WHERE c.is_apparatus
      AND c.parent_id IS NULL
      AND lower(btrim(c.title)) LIKE ANY (ARRAY['приложени%', 'подготовительные материалы%'])
),
tree AS (
    SELECT id FROM seeds
    UNION ALL
    -- Подглавы корня: их признак — наследство от него, снимается вместе с ним.
    SELECT c.id FROM chapters c JOIN tree t ON c.parent_id = t.id
)
UPDATE chapters SET is_apparatus = false
WHERE is_apparatus AND id IN (SELECT id FROM tree);
