-- Адрес разбора: слаг вместо голого id (ветка 3 направления «Разбор со
-- вклейкой»). Форма — дословно от подборок (000024): пара
-- (author_nickname, slug) уникальна, пустой ник даёт короткий адрес
-- /documents/{слаг}, непустой — длинный /documents/{ник}/{слаг}. Ключ тут
-- снимок подписи, а не ссылка на владельца, чтобы адрес пережил удаление
-- учётной записи.
--
-- Номер: в master занято по 000030 (000029 — соседняя ветка указателя,
-- 000030 — отставленные ники ветки 2). Рабочая база на 30.
--
-- varchar(255) — как collections.slug; pkg/slug.MaxLen режет основу до 60,
-- запас уходит на суффикс разведения столкновений.
ALTER TABLE documents ADD COLUMN slug VARCHAR(255) NOT NULL DEFAULT '';

-- Разборы, заведённые до этой миграции, адреса не имели вовсе. Слаг из
-- заглавия в SQL не слепить (транслитерация живёт в pkg/slug), поэтому
-- адресом становится номер строки: он уникален по построению и не требует
-- разбора заглавий. На боевом и в рабочей базе таких строк ноль — ветка
-- ставится на пустую таблицу.
UPDATE documents SET slug = 'razbor-' || id WHERE slug = '';

-- DEFAULT снимается СРАЗУ после засева: с ним вставка, забывшая слаг,
-- молча положила бы вторую строку с пустым адресом и упёрлась бы в
-- уникальность лишь на третьей — отказ на первой честнее.
ALTER TABLE documents ALTER COLUMN slug DROP DEFAULT;

ALTER TABLE documents ADD CONSTRAINT documents_author_slug_key
    UNIQUE (author_nickname, slug);
