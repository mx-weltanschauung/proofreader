-- Разметка аппарата добирает заголовки, опознаваемые ЦЕЛИКОМ у главы верхнего
-- уровня.
--
-- Миграция 000015 проставила is_apparatus по одним префиксам, и правило
-- промахнулось мимо обратного порядка слов: «Именной указатель» не начинается
-- с «указател». Замер по корпусу: у издания Выготского не было размечено
-- аппаратом НИ ОДНОЙ главы из 169 — а это ровно тот корпус, ради которого
-- заведён рычаг снятия аппарата (живой предъявитель, тикет 16).
--
-- Список повторяет models.apparatusTopTitles дословно, и оба ограничения
-- правила тоже — они куплены встречным запросом по корпусу:
--
--   целиком, а не вхождением — «содержит» утащило бы в аппарат десятки
--   настоящих работ («ПОСЛЕСЛОВИЕ К ТЕЗИСАМ…» Ленина, «Комментарии к
--   парламентским дебатам» Маркса);
--
--   только верхний уровень — «Послесловие» подглавой внутри «УДЕРЖАТ ЛИ
--   БОЛЬШЕВИКИ ГОСУДАРСТВЕННУЮ ВЛАСТЬ?» это послесловие самого Ленина, а
--   «Литература» внутри «КАРЛА МАРКСА» — его же список литературы; таких по
--   корпусу десять, и все они текст автора.
--
-- Подглава настоящего аппарата признак получает наследованием: рекурсия ниже
-- спускает его вниз от корня, ровно как в 000015.
--
-- Как и 000015, миграция только СТАВИТ true и никогда не снимает: разметка
-- правится руками, и снимающая ветка затёрла бы ручную работу.

WITH RECURSIVE tree AS (
    -- Корень: глава без родителя. Уже размеченная (000015 или рукой) остаётся
    -- корнем поддерева аппарата — иначе её подглавы признак бы не унаследовали.
    SELECT c.id,
           (c.is_apparatus OR lower(btrim(c.title)) IN (
               'именной указатель', 'предметный указатель',
               'комментарии', 'литература', 'послесловие',
               'вступительная статья', 'от редакционной коллегии'
           )) AS apparatus
    FROM chapters c
    WHERE c.parent_id IS NULL
    UNION ALL
    -- Подглава: наследует от родителя либо несёт собственную прежнюю разметку.
    -- Списка заголовков здесь намеренно нет.
    SELECT c.id, t.apparatus OR c.is_apparatus
    FROM chapters c JOIN tree t ON c.parent_id = t.id
)
UPDATE chapters SET is_apparatus = true
WHERE NOT is_apparatus
  AND id IN (SELECT id FROM tree WHERE apparatus);
