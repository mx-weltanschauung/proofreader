-- Ключ заголовка указателя (models.NormalizeIndexTitle) перестал различать
-- вид тире и пробел, стоящий не между двумя словесными знаками: «1914— 1918
-- гг.» и «1914—1918 гг.», «Социалисты - революционеры» и
-- «Социалисты-революционеры», «(«тесняки» )» и «(«тесняки»)» дают один ключ.
-- Хранимые ключи пересчитываются здесь, до следующего ввоза: вырезки
-- переносятся на новые адреса по ключам подрубрик (key_path), и ключ,
-- посчитанный прежним правилом, со свежим не сошёлся бы.
--
-- Пересчёт идёт от хранимого ключа, а не от заглавия. Ключ уже прошёл NFC,
-- регистр, ё→е и схлопывание пробелов в Go — у SQL из этого нет ни NFC, ни
-- резки по неразрывному пробелу (`\s` Postgres его не ловит). Новое правило —
-- ровно надстройка над прежним ключом, и надстраивать его здесь точно.
--
-- [[:alnum:]] совпадает со словесным знаком Go (буква, цифра, комбинирующий
-- знак) на всём, что есть в указателях (кириллица, латиница, цифры), и
-- расходится на знаках, которых в заглавиях нет: «²» (у Go цифра, у Postgres
-- нет) и комбинирующее ударение (у Go словесный знак, у Postgres нет).
-- Совпадает ТОЛЬКО при ctype базы, знающем Юникод: при ctype «C» [[:alnum:]]
-- не видит кириллицы вовсе, и миграция склеила бы все слова ключа — «не
-- рабочий» с «нерабочий», — а следующий ввоз не нашёл бы статей по ключу и
-- снёс бы их вместе с вырезками. Поэтому первая проверка ниже отказывает, а
-- не пересчитывает.
--
-- Замер 24.09.2026 по ленинскому указателю: коллизий ни у ключей понятий, ни
-- у подрубрик под общим родителем. Коллизию статей одного издания или
-- подрубрик одного родителя уронят их UNIQUE (статьи — (edition_id,
-- title_key), подрубрики — (article_id, parent_id, title_key)); у ключа
-- понятия UNIQUE нет намеренно, и два понятия разных изданий, сошедшиеся
-- ключом, пройдут — шаг 7 свяжет отсылку с любым, ввоз предупредит о
-- неоднозначности.

DO $$
BEGIN
    IF NOT ('ж' ~ '^[[:alnum:]]$') THEN
        RAISE EXCEPTION 'ctype базы не относит кириллицу к [[:alnum:]] — пересчёт ключей указателя склеил бы слова; миграция 000033 требует ctype с Юникодом (en_US.utf8 и т. п.)';
    END IF;
END $$;

-- OR REPLACE и DROP в конце: временная функция живёт, пока живёт соединение,
-- а драйвер migrate держит одно на весь прогон — подъём, откат и снова
-- подъём в одном процессе (круговые тесты миграций) иначе упали бы на
-- повторном CREATE.
CREATE OR REPLACE FUNCTION pg_temp.index_title_key_v33(k TEXT) RETURNS TEXT AS $$
    SELECT regexp_replace(translate(k, '‐‑‒–—―−', '-------'),
                          '(?<![[:alnum:]]) | (?![[:alnum:]])', '', 'g')
$$ LANGUAGE sql IMMUTABLE;

UPDATE index_concepts SET title_key = pg_temp.index_title_key_v33(title_key);
UPDATE index_concept_articles SET title_key = pg_temp.index_title_key_v33(title_key);
UPDATE index_rubrics SET title_key = pg_temp.index_title_key_v33(title_key);
UPDATE index_concept_links SET target_title_key = pg_temp.index_title_key_v33(target_title_key);

-- Шаг 7 ReplaceForEdition дословно: ключи стали грубее, и отсылка,
-- связанная прежде, связанной и остаётся (равные ключи дают равные), а
-- прежде пустые находят понятие. Ограничивать пустыми не стал: при двух
-- понятиях с одним ключом шаг 7 и так выбирает любое из них на каждом ввозе,
-- и защита здесь продержалась бы до первого ввоза. На корпусе 24.09.2026
-- ограничение не меняло ничего (замер мутацией).
UPDATE index_concept_links l
SET to_concept_id = c.id
FROM index_concepts c
WHERE c.title_key = l.target_title_key;

DROP FUNCTION pg_temp.index_title_key_v33(TEXT);
