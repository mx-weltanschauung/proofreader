-- Вложенные подрубрики предметного указателя.
--
-- В печати статья «КПСС — съезды» трёхуровневая: статья → съезд («I съезд
-- РСДРП. 1-3 (13-15) марта 1898 г. Минск») → аспект («— значение съезда»).
-- index_rubrics была плоской, и все 12 съездов стали самостоятельными
-- понятиями верхнего уровня с 1879 адресами под ними.

ALTER TABLE index_rubrics
    ADD COLUMN parent_id BIGINT REFERENCES index_rubrics(id) ON DELETE CASCADE;

-- Индекс обязателен, а не желателен: у index_references.rubric_id индекса
-- нет вовсе, и каскадное удаление подрубрик уже стоит 37 с на ленинском
-- объёме (замер прошлой ветки). Второй каскад без индекса удвоил бы цену.
CREATE INDEX idx_index_rubrics_parent_id ON index_rubrics(parent_id);

-- Уникальность переезжает с «ключ уникален В СТАТЬЕ» на «ключ уникален СРЕДИ
-- ДЕТЕЙ ОДНОГО РОДИТЕЛЯ». Без этого шага вложенность не заработала бы вовсе:
-- «значение съезда» стоит у СЕМИ съездов ленинского указателя (и
-- «организационные вопросы» — тоже у семи, всего 25 таких имён), то есть
-- семь строк с одним title_key в ОДНОЙ статье, и прежнее ограничение
-- роняло бы весь ввоз на уровне базы, сколько бы ни ослаблялась проверка в Go.
--
-- Дубль под ОДНИМ родителем остаётся отказом: адреса второй подрубрики ушли
-- бы под имя первой.
ALTER TABLE index_rubrics DROP CONSTRAINT index_rubrics_article_id_title_key_key;

-- NULLS NOT DISTINCT (PostgreSQL 15+, проект закреплён на postgres:15-alpine)
-- обязателен: у подрубрики верхнего уровня parent_id равен NULL, а при
-- обычной уникальности NULL не равен NULL — два корня с одним ключом в одной
-- статье прошли бы молча, то есть прежнее правило исчезло бы вместе со
-- старым ограничением.
ALTER TABLE index_rubrics
    ADD CONSTRAINT index_rubrics_article_parent_title_key
    UNIQUE NULLS NOT DISTINCT (article_id, parent_id, title_key);
