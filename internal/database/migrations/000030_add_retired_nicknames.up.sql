-- Отставленные ники: имена ушедших читателей, которые нельзя занять заново.
--
-- Уход читателя (DELETE /api/auth/me) сносит строку users, но подпись под
-- тем, что он оставил, держится СНИМКОМ (documents.author_nickname,
-- collections.author_nickname) — она переживает владельца намеренно. Без
-- этой таблицы ник освобождался вместе со строкой, следующий желающий его
-- занимал, и опубликованный чужой разбор продолжал печатать «Собрал читатель
-- ‹ник›» — теперь уже про живого человека, который этого не писал.
--
-- Это тот же довод, которым models.ValidateNickname запрещает смешивать
-- кириллицу с латиницей: гомоглиф иначе подписывает чужой текст чужим
-- именем. Уход приводил к тому же исходу другой дверью.
--
-- Ключ — нормализованная форма, то же выражение, что у вычисляемого столбца
-- users.nickname_key (lower(normalize(nickname, NFKC))), и отставка ставится
-- копированием ГОТОВОГО значения этого столбца: сойтись они обязаны байт в
-- байт, иначе «уходящий» и «УХОДЯЩИЙ» разъедутся на отставке, хотя в users
-- они один и тот же читатель.
--
-- Видимая форма хранится рядом — она не участвует в сравнении и нужна
-- человеку, читающему таблицу глазами (жалоба приходит с ником, а не с
-- ключом).
--
-- Номер 000030, а не 000029: 000029 занят соседней веткой
-- (lenin-index-backend, add_link_target_title_key) — рабочие копии делят одну
-- базу, и номер берётся по соседям, а не по последнему в своём дереве.
CREATE TABLE retired_nicknames (
    nickname_key text        PRIMARY KEY,
    nickname     varchar(64) NOT NULL,
    retired_at   timestamptz NOT NULL DEFAULT now()
);
