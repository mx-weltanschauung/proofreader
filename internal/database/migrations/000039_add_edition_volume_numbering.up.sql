-- Нумерация томов собрания: печатная или условная.
--
-- 'printed' — номер тома стоит на книге, читатель найдёт «т. 24» в
-- библиотеке; читальня печатает его в подписях, цитате, выгрузках.
-- 'order'   — номер условный: у книг собрания общей нумерации нет
-- (стенограммы пленумов и конгрессов разных лет), и volume_number заведён
-- только затем, чтобы поставить книги по порядку на полке и держать
-- уникальность внутри издания. Читателю его не печатает ни одна поверхность:
-- «т. 24» в цитате отправил бы его искать том, которого нет в природе.
--
-- Текстом с перечнем, а не bool: значение читается в ответе API без
-- расшифровки («volume_numbering": "order", а не отрицание вроде
-- «numbers_hidden»: true), и третий вид нумерации, если понадобится,
-- встанет в CHECK, а не вторым флагом рядом с первым. Умолчание —
-- 'printed': все собрания до этой миграции нумерованы по печати.
ALTER TABLE editions
    ADD COLUMN volume_numbering text NOT NULL DEFAULT 'printed'
        CONSTRAINT editions_volume_numbering_check
        CHECK (volume_numbering IN ('printed', 'order'));
