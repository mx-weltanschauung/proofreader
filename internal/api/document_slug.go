package api

import "proofreader/pkg/slug"

// reservedDocumentSlugs — слаги, которых у разбора быть не может, потому что
// маршрутизация разберёт такой адрес иначе.
//
// Две разные причины в одном списке:
//   - «mine», «review», «new», «edit» — литеральные сегменты, объявленные
//     РАНЬШЕ общего шаблона (на сервере — подроутером reader/staffEarly, на
//     клиенте — по специфичности React Router). Сотруднический разбор со
//     слагом «mine» не открылся бы никогда;
//   - «view», «cuts», «submit», «unpublish», «approve», «reject» — вторые
//     сегменты КОРОТКОГО адреса: /documents/{слаг}/view объявлен раньше
//     длинного /documents/{ник}/{слаг}, и читательский разбор со слагом
//     «view» достался бы чужому маршруту.
//
// Список закрытый и проверяется сторожем задачи 3: маршрут, добавивший
// литеральный сегмент и забывший это слово, ловится там, а не читателем.
var reservedDocumentSlugs = map[string]bool{
	"mine": true, "review": true, "new": true, "edit": true,
	"view": true, "cuts": true, "submit": true, "unpublish": true,
	"approve": true, "reject": true,
}

// documentSlugBase — основа адреса разбора из его заглавия.
//
// Слаг лепит сервер, а не автор (решение владельца 20.09.2026): читатель
// пишет заглавие, а не адрес, и слаг-пустышка вроде «asdf» иначе осталась бы
// навсегда — править её некому. Основа замораживается при создании:
// переименование заглавия адрес не двигает, иначе внешняя ссылка, ради
// которой вся ветка и затеяна, протухала бы молча.
//
// Разведение столкновений (суффикс -2, -3…) делает не эта функция, а
// вставка в репозитории: только она видит их атомарно. Зарезервированное имя
// отодвигается суффиксом -razbor, а не отдаётся на разведение: «view-2»
// читалось бы как второй разбор с заглавием «view», которого нет.
func documentSlugBase(title string) string {
	base := slug.Text(title)
	if base == "" {
		return "razbor"
	}
	if reservedDocumentSlugs[base] {
		return base + "-razbor"
	}
	return base
}
