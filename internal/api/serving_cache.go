package api

import (
	"log"

	"proofreader/internal/pagecache"
)

// crawlerCaches — краулерская половина: страницы и карточки og:image, которые
// seo.Handler держит в памяти. Интерфейсом, а не типом, чтобы internal/api не
// зависел от internal/seo ради одного метода и чтобы тест мог подставить свой.
type crawlerCaches interface {
	Purge() (pages int, cards int)
}

// ServingCache — всё, что отдаётся читателю не из базы, а из кэша.
//
// Заведён ради одного вопроса: что обязано умереть вместе со снятым томом.
// Кэшей отдачи три, все с разными сроками годности и ни одного с путём
// инвалидации по записи:
//
//	файловый кэш глав на диске — час (pagecache);
//	страницы краулеру в памяти — час (seo.cacheTTL);
//	карточки og:image в памяти — СУТКИ (seo.cardCacheTTL).
//
// До этого типа снос тома не трогал ни один из них, и снятый том продолжал
// отдаваться главами до часа, а превью ссылки в мессенджерах — до суток.
// Адресно догнать его после сноса уже нечем: CacheHandler.PurgeChapter
// резолвит границы главы из базы, а строки нет.
type ServingCache struct {
	pages   *pagecache.Store
	crawler crawlerCaches
}

func NewServingCache(pages *pagecache.Store, crawler crawlerCaches) *ServingCache {
	return &ServingCache{pages: pages, crawler: crawler}
}

// DropWork сбрасывает всё, что могло сохранить текст тома.
//
// Файловый кэш бьётся адресно — по каталогу тома; краулерский сбрасывается
// целиком, потому что ключ там путь читальни, и собрать все пути снятого тома
// (главы, полосы, карточки) после удаления строки уже неоткуда.
//
// Ошибки не возвращает, а пишет в журнал: зовут её последним шагом сноса,
// когда данные уже удалены, и отвечать на неё отказом означало бы сказать
// вызывающему «снятие не удалось» про снятие, которое удалось. Худшее, чем
// это кончится, — кусок кэша доживёт до своего часа.
//
// nil-приёмник допустим и означает «кэшей нет»: так собраны обработчики в
// части тестов.
func (c *ServingCache) DropWork(workID int64) {
	if c == nil {
		return
	}
	if c.pages != nil {
		files, bytes, err := c.pages.PurgeWork(workID)
		if err != nil {
			log.Printf("сброс файлового кэша работы %d: %v", workID, err)
		} else if files > 0 {
			log.Printf("сброшен файловый кэш работы %d: %d файлов, %d байт", workID, files, bytes)
		}
	}
	if c.crawler != nil {
		if pages, cards := c.crawler.Purge(); pages > 0 || cards > 0 {
			log.Printf("сброшен краулерский кэш: %d страниц, %d карточек", pages, cards)
		}
	}
}

// DropCrawler сбрасывает только краулерскую половину — страницы и карточки
// og:image, которые seo.Handler держит в памяти, — без файлового кэша глав.
// Для разбора это ЕДИНСТВЕННАЯ уместная половина: у него нет полос и нет
// файлового кэша, который бился бы адресно по каталогу тома, как в DropWork.
//
// Сброс тотальный по тому же доводу, что у DropWork: ключ кэша — путь
// читальни, а после снятия/удаления строки собрать все пути, которые
// разбор занимал (страница, витрина, карточка, карта сайта), уже неоткуда.
// Дёшево именно потому, что тотальный сброс тут не бьёт по живым читателям:
// краулеров, которые вообще заходят на эти страницы, — десятки в сутки, и
// пересобрать их кэш заново стоит немного рядом с ценой часа отдачи снятого
// текста по жалобе, ради которой этот метод и заведён.
//
// Ошибок не возвращает по той же причине, что и DropWork: зовут её после
// того, как снятие/удаление в базе уже удалось, и превращать это в отказ
// значило бы соврать вызывающему про операцию, которая на самом деле прошла.
//
// nil-приёмник допустим и означает «кэшей нет» — как и у DropWork.
func (c *ServingCache) DropCrawler() {
	if c == nil || c.crawler == nil {
		return
	}
	if pages, cards := c.crawler.Purge(); pages > 0 || cards > 0 {
		log.Printf("сброшен краулерский кэш: %d страниц, %d карточек", pages, cards)
	}
}
